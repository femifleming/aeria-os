#!/usr/bin/env python3
"""Generates twister.asm and twister_test.asm (AERIA TWISTER: the Balloon Shop's whirlwind,
MoreWeather.h `Twister`, in fixed point).

    python3 twister/gen.py          (host, no dependencies)   -- test.py imports this and rebuilds

twister.asm       the hardware build: the ring's base is the word X:$213 points to, used as an X address
twister_test.asm  the same source with the ring at X:$10000 (dsp_host hands out a Y base); one line differs
"""
import math
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import wxlib as W  # noqa: E402
from wxlib import q, n  # noqa: E402

HERE = Path(__file__).resolve().parent
FS = W.FS

# ---- sizes ---------------------------------------------------------------------------------------
RING = 4096                 # X words: one stereo ring, L even / R odd (2,048 frames); base a multiple of RING
WINDOW = 2032               # frames (46.1 ms; the plugin's 60 ms needs 5,324 words at an 8K-aligned base)
HALF = WINDOW // 2
TAP0 = 2                    # the plugin's 2 + phase x window
CLR_BLOCKS = 16
CLR_WORDS = RING // CLR_BLOCKS
TEST_XRING = 0x10000

# ---- the plugin's event ------------------------------------------------------------------------------
T_RND = 10.0                # RND: 10 s x 2^r, r uniform 0..1 (the plugin: 10 + 10 r; same range, log-even)
T_KNOB = 2.0                # TIME v >= 1: 2 s x 2^(v/32)
T_OCT = 32.0
U_SHIFT = 12                # 1/blocks is built as K x 2^-e, K scaled by 2^12
IN_PART, OUT_PART = 0.12, 0.15
SEMIS = 7                   # RISE's default (the plugin)
SPIN_REST, SPIN_TOP = 0.3, 5.0      # Hz: 0.3 + 5 u^2 out at SPIN 64
DEPTH, UP = 0.8, 0.3
TRIG = 64 << 16


def _powfit():
    """u^1.3 ~ c1 u + c2 u^2 + c3 u^3 on 0..1 (least squares)."""
    xs = [i / 500 for i in range(501)]
    rows = [[x, x * x, x ** 3] for x in xs]
    ys = [x ** 1.3 for x in xs]
    A = [[sum(r[i] * r[j] for r in rows) for j in range(3)] for i in range(3)]
    b = [sum(r[i] * y for r, y in zip(rows, ys)) for i in range(3)]
    for i in range(3):
        p = A[i][i]
        A[i] = [v / p for v in A[i]]
        b[i] /= p
        for j in range(3):
            if j != i:
                f = A[j][i]
                A[j] = [u - f * v for u, v in zip(A[j], A[i])]
                b[j] -= f * b[i]
    return b


POW_C = _powfit()


def pow13(u):
    return POW_C[0] * u + POW_C[1] * u * u + POW_C[2] * u ** 3


POW_ERR = max(abs(pow13(i / 1000) - (i / 1000) ** 1.3) for i in range(1001))


def smooth(x):
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


def event(u, rise=SEMIS, spin=64):
    """The plugin's curves at progress u: (amount, semitones, spin Hz)."""
    out = smooth((1 - u) / OUT_PART)
    a = min(smooth(u / IN_PART), out)
    return a, rise * u ** 1.3 * out, SPIN_REST + SPIN_TOP * spin / 64 * u * u * out


def seconds(v, r=0.5):
    """TIME: v = 0 the plugin's random 10..20 s (r its draw), else 2 s x 2^(v/32)."""
    return T_RND * 2 ** r if v == 0 else T_KNOB * 2 ** (v / T_OCT)


ST = W.State('ST XB WP RNG ARM UH UL DUH DUL PHH PHL NIH NIL SPH AL BL AR BR DAL DBL DAR DBR '
             'W0 W1 W2 W3 WW1 WW2 AEN OUTE T1 T2 HSN RSK')

TAPS = '''        clr     a
        clr     b
        move    {W0},y0
        move    x:(r3)+,x0
        mac     y0,x0,a
        move    x:(r3)+,x0
        mac     y0,x0,b
        move    {W1},y0
        move    x:(r3)+,x0
        mac     y0,x0,a
        move    x:(r3)+,x0
        mac     y0,x0,b
        move    {W2},y0
        move    x:(r3)+,x0
        mac     y0,x0,a
        move    x:(r3)+,x0
        mac     y0,x0,b
        move    {W3},y0
        move    x:(r3)+,x0
        mac     y0,x0,a
        move    x:(r3)+,x0
        mac     y0,x0,b
'''

TEMPLATE = r'''; CYCLES_FORWARD_BRANCHES
; AERIA TWISTER {=BUILDNOTE} -- generated by twister/gen.py, do not edit.
; The Balloon Shop's whirlwind (MoreWeather.h, Twister): one event of 10 .. 20 s. The pitch climbs
; RISE semitones (x u^1.3) and falls back in the last 15 %, through two Hann-windowed taps half a
; window apart on a {=WINDOW}-frame window, while the sound whirls from side to side, faster and
; faster (0.3 Hz .. 0.3 + SPIN), and swells up to x 1.3.
;
;  knob 0 AMT   the trigger: going from under 64 to 64 or more starts ONE event; the knob is not
;               looked at again until the event has ended, and must come back under 64 to arm the next
;  knob 1 RISE  semitones at the top, 0 .. 12 (7 = the plugin)
;  knob 2 SPIN  spin added at the top: 5 Hz x v/64 (64 = the plugin: 0.3 -> 5.3 Hz)
;  knob 3 TIME  0 = RND, 10 s x 2^r (r random 0..1: the plugin's 10 .. 20 s); else 2 s x 2^(v/32)
;
; No event: REST, the routine returns after the trigger test (output = input, bit for bit).
; A start clears the ring over {=CLRB} dry calls ({=CLRW} words each), then the event runs; its
; envelopes, pitch, spin and gains are set once a call (16 frames), the gains ramped a frame.
; Read: 4-point Hermite, weights once a frame for both taps (half a window apart = whole frames).
;
; X ring: {=RING} words, L even / R odd, base a multiple of {=RING}: {=BASENOTE}
; r7: {=STATEDOC}

init:
        move    #>$ffffff,m4
        move    r7,r4
        clr     a
        do      #64,>twzero
        move    a,x:(r4)+
twzero:
        nop
{=GETBASE}        move    a,{XB}
        move    a,{WP}
        move    #>$00a11c,a
        move    a,{RNG}
        move    #>$1,a
        move    a,{ARM}
        rts
proc:
        move    {ST},a
        tst     a
        bne     twawake
; ---- REST: the trigger
        move    x:(r6),a
        cmp     {=TRIG},a
        bge     twhigh
        move    #>$1,a
        move    a,{ARM}                 ; under 64: armed
        rts
twhigh:
        move    {ARM},a
        tst     a
        bne     twstart
        rts
twstart:
; ---- one starts: its length, then {=CLRB} clearing calls
        clr     a
        move    a,{ARM}
        move    a,{UH}
        move    a,{UL}
        move    a,{PHH}
        move    a,{PHL}
        move    a,{BL}
        move    a,{BR}
        move    #>$400000,a
        move    a,{AL}
        move    a,{AR}
        move    {XB},a
        move    a,{WP}
        move    x:(r6+$3),a
        tst     a
        bne     twfixed
        bsr     twrand                  ; RND: 2^-r
        asr     #$5,a,a
        move    a1,a
        bsr     twexp
        move    b,x0
        move    {=KRND},y0
        bra     twlen
twfixed:
        asr     #$3,a,a                 ; (v/32)/32
        move    a1,a
        bsr     twexp
        move    b,x0
        move    {=KFIX},y0
twlen:
        mpy     y0,x0,a
        asr     {=USHIFT},a,a           ; progress a call, 48 bits
        move    a1,{DUH}
        move    a0,{DUL}
        move    x:(r6+$1),a             ; RISE starts where the knob is (glided from here on)
        move    a,{RSK}
        move    {=CLRBN},a
        move    a,{ST}
        rts
twawake:
        blt     twrun
; ---- clearing: call n (16 .. 1) clears words (n - 1) * {=CLRW} ..
        sub     #>$1,a
        move    a,{ST}
        asl     {=CLRSH},a,a
        move    {XB},x0
        add     x0,a
        move    a1,r4
        move    #>$ffffff,m4
        clr     b
        do      {=CLRWN},>twclr
        move    b,x:(r4)+
twclr:
        nop
        move    {ST},a
        tst     a
        bne     twkeep
        move    #>$ffffff,a             ; cleared: RUN from the next call
        move    a,{ST}
twkeep:
        rts
twrun:
; ======== the event, once a call ========
        move    {UH},a
        move    {UL},a0
        move    {DUH},x1
        move    {DUL},x0
        add     x,a
        move    #>$7fffff,x0
        cmp     x0,a
        blt     twon
        clr     a                       ; over: REST (the last call's gains were dry within the ramp's LSBs)
        move    a,{ST}
        rts
twon:
        move    a1,{UH}
        move    a0,{UL}
; out = smoothstep((1 - u)/0.15), amount = min(smoothstep(u/0.12), out)
        move    #>$7fffff,a
        move    {UH},x0
        sub     x0,a
        move    a,x0
        move    {=KOUT},y0
        mpy     y0,x0,a
        asl     #$3,a,a
        move    a,x0
{=SMOOTHSTEP}        move    a,x0
        move    x0,{OUTE}
        move    {UH},x0
        move    {=KIN},y0
        mpy     y0,x0,a
        asl     #$4,a,a
        move    a,x0
{=SMOOTHSTEP}        move    {OUTE},x0
        cmp     x0,a
        tgt     x0,a
        move    a,{AEN}
; pitch: semitones = RISE x u^1.3 x out (u^1.3 as a cubic); ratio = 2^(semis/12)
        move    {UH},x0
        move    {=PC3},y0
        mpy     y0,x0,a
        add     {=PC2},a
        move    a,y0
        mpy     y0,x0,a
        add     {=PC1},a
        move    a,y0
        mpy     y0,x0,a                 ; u^1.3
        move    a,x0
        move    {OUTE},y0
        mpy     y0,x0,a
        move    a,x0
        move    x:(r6+$1),a             ; RISE glided 1/16 a call (5.8 ms): a jumped knob slides, it does not step
        move    {RSK},b
        sub     b,a
        asr     #$4,a,a
        add     a,b
        move    b,{RSK}
        move    b,y0
        mpy     y0,x0,a                 ; x RISE/128
        move    a,x0
        move    {=KRISE},y0
        mpy     y0,x0,a
        asl     #$4,a,a                 ; E = semis/12, 0..1
        move    a,x0
        move    #>$7fffff,a
        sub     x0,a
        asr     #$5,a,a                 ; (1 - E)/32
        move    a1,a
        bsr     twexp
        asl     b
        sub     #>$7fffff,b             ; ratio - 1
        move    #>$0,x0
        tst     b
        tmi     x0,b
        move    b,x0
        move    {=KWIN},y0
        mpy     y0,x0,a
        asr     #$a,a,a
        neg     a                       ; the phase falls by (ratio - 1)/window a frame
        move    a1,{NIH}
        move    a0,{NIL}
; spin: the angle (as a fraction of pi) moves 0.3 + SPIN u^2 out Hz
        move    {UH},x0
        mpy     x0,x0,a
        move    a,x0
        move    {OUTE},y0
        mpy     y0,x0,a
        move    a,x0
        move    x:(r6+$2),y0
        mpy     y0,x0,a
        move    a,x0
        move    {=KSPIN},y0
        mpy     y0,x0,a
        add     {=KSPIN0},a
        move    {SPH},b
        add     b,a
        move    a1,{SPH}                ; wraps at +-pi
        move    a1,b                    ; sin: fold to +-pi/2
        abs     b
        move    #>$400000,x0
        cmp     x0,b
        ble     twfold
        neg     b
        add     #>$7fffff,b
twfold:
        asl     b
        move    b,x0
        bsr     twsin                   ; a = 0.5 sin(|angle|)
        move    {SPH},b
        tst     b
        bge     twsgn
        neg     a
twsgn:
        move    a,{HSN}
; gains: g/2 = (0.5 + 0.15 a)(1 - 0.8 a (0.5 +- 0.5 s)); out = 2 (A dry + B wet), A = g/2 (1 - a), B = g/2 a
        move    {AEN},x0
        move    {=KUP},y0
        mpy     y0,x0,a
        add     #>$400000,a
        move    a,{T1}                  ; up/2
        move    {=KDEPTH},y0
        mpy     y0,x0,a
        move    a,{T2}                  ; 0.8 a
; left
        move    {HSN},a
        add     #>$400000,a
        move    a,x0
        move    {T2},y0
        mpy     y0,x0,a
        neg     a
        add     #>$7fffff,a
        move    a,x0
        move    {T1},y0
        mpy     y0,x0,a
        move    a,y0                    ; g/2
        move    {AEN},x1
        mpy     x1,y0,a
        move    {BL},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DBL}
        move    #>$7fffff,a
        sub     x1,a
        move    a,x0
        mpy     y0,x0,a
        move    {AL},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DAL}
; right
        move    #>$400000,a
        move    {HSN},x0
        sub     x0,a
        move    a,x0
        move    {T2},y0
        mpy     y0,x0,a
        neg     a
        add     #>$7fffff,a
        move    a,x0
        move    {T1},y0
        mpy     y0,x0,a
        move    a,y0
        mpy     x1,y0,a
        move    {BR},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DBR}
        move    #>$7fffff,a
        sub     x1,a
        move    a,x0
        mpy     y0,x0,a
        move    {AR},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DAR}
; ======== the frames ========
        move    {=RINGM},m1
        move    {=RINGM},m3
        move    {WP},r1
        move    #>$1,n0
        do      n7,>twframes
        move    x:(r0),a
        move    a,x:(r1)+
        move    x:(r0+n0),a
        move    a,x:(r1)+
; phase -= (ratio - 1)/window, wrapped 0..1 (48 bits)
        move    {PHH},a
        move    {PHL},a0
        move    {NIH},x1
        move    {NIL},x0
        add     x,a
        and     #>$7fffff,a
        move    a1,{PHH}
        move    a0,{PHL}
; the Hann pair: tap 1 x sin^2(pi phase), tap 2 x the rest
        move    a1,b
        sub     #>$400000,b
        abs     b
        asl     #$2,b,b
        neg     b
        add     #>$7fffff,b
        move    b,x0                    ; 1 - |4 phase - 2|
{=SINLINES}        add     #>$400000,b
        move    b,x0
        move    x0,{WW1}
        move    #>$7fffff,b
        sub     x0,b
        move    b,{WW2}
; tap 1 sits phase x window frames back (+ 2): whole frames to n, the fraction to the weights
        move    {PHH},x0
        move    {=WINN},y0
        mpy     y0,x0,a
        move    a1,x1                   ; whole frames
        move    a0,b
        not     b
        lsr     b
        move    b1,x0                   ; t = 1 - fraction
; Hermite weights: W0 = t2 - (t3 + t)/2, W2 = 2 t2 + (t - 3 t3)/2, W3 = (t3 - t2)/2, W1 = 1 - the rest
        mpy     x0,x0,a
        move    a,y1                    ; t2
        mpy     x0,y1,b
        move    b,y0                    ; t3
        sub     y1,b
        asr     b
        move    b,{W3}
        move    b,a
        move    y0,b
        add     x0,b
        asr     b
        neg     b
        add     y1,b
        move    b,{W0}
        add     b,a
        move    y0,b
        asl     b
        add     y0,b
        neg     b
        add     x0,b
        asr     b
        add     y1,b
        add     y1,b
        move    b,{W2}
        add     b,a
        move    #>$7fffff,b
        sub     a,b
        move    b,{W1}
; tap 1
        move    x1,a
        add     {=TAPOFS},a
        move    a1,n1
        move    a1,n3
        lua     (r1)-n1,r3
        lua     (r3)-n3,r3
{=TAPS}        move    a,{T1}
        move    b,{T2}
; tap 2: half a window further round
        move    x1,b
        add     {=HALFN},b
        move    b,y1
        sub     {=WINN},b
        tmi     y1,b
        add     {=TAPOFS},b
        move    b1,n1
        move    b1,n3
        lua     (r1)-n1,r3
        lua     (r3)-n3,r3
{=TAPS}        move    {T1},x1
        move    {T2},y1
        move    {WW1},y0
        move    a,x0
        mpy     x1,y0,a
        move    {WW2},x1
        mac     x1,x0,a
        move    b,x0
        mpy     y1,y0,b
        mac     x1,x0,b
        move    a,x1                    ; wet L
        move    b,y1                    ; wet R
; left: 2 (A dry + B wet), A and B ramped to this call's values
        move    {AL},b
        move    {DAL},y0
        add     y0,b
        move    b,{AL}
        move    b,y0
        move    x:(r0),x0
        mpy     y0,x0,a
        move    {BL},b
        move    {DBL},y0
        add     y0,b
        move    b,{BL}
        move    b,y0
        mac     x1,y0,a
        asl     a
        move    a,x:(r0)+
; right
        move    {AR},b
        move    {DAR},y0
        add     y0,b
        move    b,{AR}
        move    b,y0
        move    x:(r0),x0
        mpy     y0,x0,a
        move    {BR},b
        move    {DBR},x0
        add     x0,b
        move    b,{BR}
        move    b,x0
        mac     x0,y1,a
        asl     a
        move    a,x:(r0)+
twframes:
        nop
        move    r1,{WP}
        move    #>$ffffff,m1
        move    #>$ffffff,m3
        rts
; ---- subroutines (after their callers) ----
{=RANDSUB}{=EXPSUB}{=SINSUB}'''


def build(out='twister.asm', quiet=True):
    test = out != 'twister.asm'
    getbase = (f'        move    {n(TEST_XRING)},a\n' if test else
               '        move    x:>$213,r4\n        nop\n        move    x:(r4),a\n')
    blocks_s = FS / W.BLOCK
    c = dict(
        BUILDNOTE='(TEST: ring at X:$10000)' if test else '',
        BASENOTE='X:$10000 (test)' if test else 'the word X:$213 points to (an X address on this effect)',
        GETBASE=getbase, WINDOW=WINDOW, RING=RING, CLRB=CLR_BLOCKS, CLRW=CLR_WORDS, STATEDOC=ST.doc(),
        CLRBN=n(CLR_BLOCKS), CLRWN=n(CLR_WORDS), CLRSH=f'#${int(math.log2(CLR_WORDS)):x}', RINGM=n(RING - 1),
        TRIG=n(TRIG), USHIFT=f'#${U_SHIFT:x}',
        KRND=q((1 << U_SHIFT) / (T_RND * blocks_s)), KFIX=q((1 << U_SHIFT) / (T_KNOB * blocks_s)),
        KOUT=q(1 / OUT_PART / 8), KIN=q(1 / IN_PART / 16), SMOOTHSTEP=W.SMOOTHSTEP,
        PC1=q(POW_C[0]), PC2=q(POW_C[1]), PC3=q(POW_C[2]),
        KRISE=q(128 / 12 / 16), KWIN=q(1024 / WINDOW),
        KSPIN=q(2 * W.DT * SPIN_TOP * 2), KSPIN0=q(2 * W.DT * SPIN_REST),
        KUP=q(UP / 2), KDEPTH=q(DEPTH),
        SINLINES=W.sin_lines(acc='b'), WINN=n(WINDOW), HALFN=n(HALF), TAPOFS=n(TAP0 + 3),
        TAPS=TAPS,
        RANDSUB=W.rand_sub('twrand', '{RNG}'), EXPSUB=W.exp2_sub('twexp', 'twpow'), SINSUB=W.sin_sub('twsin'),
    )
    assert WINDOW + TAP0 + 4 <= RING // 2 and WINDOW % 2 == 0
    src = W.render(W.render(W.render(TEMPLATE, ST, c), ST, c), ST, c)
    W.write(HERE / out, src, quiet)
    return src


BUILDS = ('twister.asm', 'twister_test.asm')

if __name__ == '__main__':
    for b in BUILDS:
        build(b, quiet=False)
    print(f'u^1.3 cubic {POW_C}, max error {POW_ERR:.4f} ({SEMIS * POW_ERR * 100:.1f} cents at RISE 7)')
