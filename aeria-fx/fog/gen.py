#!/usr/bin/env python3
"""Generates fog.asm and fog_test.asm (AERIA FOG: the Balloon Shop's fog, MoreWeather.h `Fog`).

    python3 fog/gen.py          (host, no dependencies)   -- test.py imports this and rebuilds

fog.asm       the hardware build: its three rings at base + $000 / $200 / $600, for a base that
              is $a00 past a multiple of $1000 (Y:$8a00: rings at $8a00, $8c00, $9000)
fog_test.asm  the same source with the rings at base + $000 / $400 / $1000 for dsp_host's
              instance buffer (Y:$4000); only those literals and the clearing count differ
"""
import math
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import wxlib as W  # noqa: E402
from wxlib import q, n  # noqa: E402

HERE = Path(__file__).resolve().parent
FS = W.FS

# ---- the plugin's six allpasses, in frames at 44.1 kHz --------------------------------------------
MS = (3.1, 5.3, 7.9, 11.3, 14.9, 19.1)
LEN = tuple(max(2, int(ms * 0.001 * FS)) for ms in MS)          # 136 233 348 498 657 842
G_PLUGIN = 0.6
HZ_TOP, HZ_FOG = 18000.0, 4500.0
SHIFT = 3                   # headroom: the allpasses run on the input / 8

# ---- three rings (stage: ring). Each ring holds, a stage after the other, [L line][R line], and is one
# word longer than their sum, so every line's pointer comes back one word lower each frame by itself.
RING_OF = {0: 'B', 1: 'C', 2: 'B', 3: 'A', 4: 'A', 5: 'A'}
RING_WORDS = {r: 1 + 2 * sum(LEN[s] for s in range(6) if RING_OF[s] == r) for r in 'ABC'}   # 3995 969 467
RING_ALIGN = {'A': 4096, 'B': 1024, 'C': 512}
OFFSETS = {'fog.asm': {'C': 0x000, 'B': 0x200, 'A': 0x600},         # base = $xa00
           'fog_test.asm': {'C': 0x000, 'B': 0x400, 'A': 0x1000}}   # base = $4000
TOTAL = {'fog.asm': 0x1600, 'fog_test.asm': 0x2000}                 # words claimed from the base (cleared)
CLR_WORDS = 256
AM_SNAP = 0x40
GATE_S = 1.5                # input exactly 0 this long: calls of all-0 input are skipped (out = in = 0)
GATE_CALLS = round(GATE_S * FS / 16)
BLUR_K = G_PLUGIN * 128 / 100           # g = 0.6 x v/100
DARK_OCT = 32.0                         # DARK: v/32 octaves down from 18 kHz at full fog (64 = 4.5 kHz)


def blur_g(v):
    return G_PLUGIN * v / 100


def dark_hz(v, amt=1.0):
    return HZ_TOP * 2 ** (-(v / DARK_OCT) * amt)


def lp_coef(hz):
    return 1 - math.exp(-2 * math.pi * min(hz, 0.45 * FS) / FS)


def stage_start(s):
    """Offset of stage s's L line inside its ring."""
    return 2 * sum(LEN[k] for k in range(s) if RING_OF[k] == RING_OF[s])


ST = W.State('ST YB AMH AML WM DW LPA LPL LPR GG P0 P1 P2 P3 P4 P5 DLAST ALAST BLK R6S WT SIL GC DG')


def stage(k):
    r = f'r{k + 1}'
    nn = f'n{k + 1}'
    return f'''; stage {k}: {LEN[k]} frames ({MS[k]} ms)
        move    y:({r})-{nn},x0
        mac     y0,x0,a
        move    a,y:({r})+{nn}
        move    a,x1
        move    x0,a
        mac     -x1,y0,a
        move    y:({r}+{nn}),x0
        mac     y0,x0,b
        move    b,y:({r})-
        move    b,x1
        move    x0,b
        mac     -x1,y0,b
'''


TEMPLATE = r'''; CYCLES_FORWARD_BRANCHES
; AERIA FOG {=BUILDNOTE} -- generated by fog/gen.py, do not edit.
; The Balloon Shop's fog (MoreWeather.h, Fog): six short allpasses in a row blur every attack
; (about a tenth of a second of smear, no tail) and the highs sink; each side through its own
; six lines, same lengths, same filter.
;
;  knob 0 AMT   the weather's fade 0..127 = 0..1: mix = smoothstep(1.5 amt); lowpass 18 kHz x 2^-(amt x DARK/32)
;  knob 1 BLUR  allpass gain g = 0.6 x v/100 (100 = the plugin's 0.6; 127 = 0.76)
;  knob 2 DARK  where the highs sink to at full fog: 18 kHz x 2^-(v/32) (64 = 4.5 kHz, the plugin; 0 = no lowpass)
;
; AMT 0 and settled: REST, the routine returns at once (output = input, bit for bit). Coming up
; from rest the lines are cleared over {=CLRB} dry calls ({=CLRW} words each), then it runs.
; The lines run on the input / 8 (an allpass's inside swings 2.5 x its input at g = 0.6).
;
; Y: three rings from the base X:$213 points to (words used / reserved):
;   C at base + ${=OFFC}: stage 1                 {=RWC} / 512
;   B at base + ${=OFFB}: stages 0, 2             {=RWB} / 1024
;   A at base + ${=OFFA}: stages 3, 4, 5          {=RWA} / 4096
; each ring's first word must sit on a multiple of its reserved size; {=TOTAL} words in all.
; In a ring a stage's L line and R line follow each other; the ring is one word longer than its
; lines, so each stage's pointer (r1..r6) lands one word lower every frame with no extra code.
; r7: {=STATEDOC}

init:
        move    #>$ffffff,m4
        move    r7,r4
        clr     a
        do      #64,>fgzero
        move    a,x:(r4)+
fgzero:
        nop
        move    x:>$213,r4
        nop
        move    x:(r4),a
        move    a,{YB}
        move    #>$ffffff,a
        move    a,{DLAST}
        rts
proc:
        move    {ST},a
        tst     a
        bne     fgawake
        move    x:(r6),a
        tst     a
        bne     fgwake
        rts                             ; REST: nothing touched
fgwake:
        clr     a
        move    a,{AMH}
        move    a,{AML}
        move    a,{WM}
        move    a,{LPL}
        move    a,{LPR}
        move    a,{SIL}
        move    #>$000003,a             ; the lowpass is looked at on the first running call
        move    a,{BLK}
        move    {=LPOPEN},a
        move    a,{LPA}
        move    x:(r6+$1),x0
        move    {=BLURK},y0
        mpy     y0,x0,a
        move    a,{GG}
        move    a,{GC}
        move    #>$ffffff,a
        move    a,{DLAST}
{=PINIT}        move    {=CLRBN},a
        move    a,{ST}
        rts
fgawake:
        blt     fgrun
; ---- clearing: call n ({=CLRB} .. 1) clears words (n - 1) * {=CLRW} ..
        sub     #>$1,a
        move    a,{ST}
        asl     #$8,a,a
        move    {YB},x0
        add     x0,a
        move    a1,r4
        move    #>$ffffff,m4
        clr     b
        do      {=CLRWN},>fgclr
        move    b,y:(r4)+
fgclr:
        nop
        move    {ST},a
        tst     a
        bne     fgkeep
        move    #>$ffffff,a             ; cleared: RUN from the next call
        move    a,{ST}
fgkeep:
        rts
fgrun:
; ---- amount: knob / 127, glided (1/64 a call = 23 ms, 48 bits); at 0 and settled -> REST
        move    x:(r6),x0
        move    #>$408102,y0
        mpy     y0,x0,a
        asl     a
        move    {AMH},b
        move    {AML},b0
        sub     b,a
        asr     #$6,a,a
        add     a,b
        move    b1,{AMH}
        move    b0,{AML}
        move    x:(r6),a
        tst     a
        bne     fggo
        move    {AMH},a
        cmp     {=AMSNAP},a
        bge     fggo
        clr     a
        move    a,{ST}
        rts
fggo:
; mix = smoothstep(min(1, 1.5 amt)), ramped over the call
        move    {AMH},a
        move    a,b
        asr     b
        add     b,a
        move    a,x0
{=SMOOTHSTEP}        move    a,x0
        move    x0,a
        move    {WM},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DW}
; the slow knobs, a job a call: calls 1 and 3 of every 4 read BLUR; call 0 looks whether the amount or DARK
; moved and takes hz / 18 kHz, call 2 the lowpass coefficient from it
        move    {BLK},a
        add     #>$1,a
        and     #>$000003,a
        move    a1,{BLK}
        tst     a
        beq     fgchk
        cmp     #>$000002,a
        beq     fgfin
        move    x:(r6+$1),x0
        move    {=BLURK},y0
        mpy     y0,x0,a
        move    {GG},b                  ; glided 1/8 a look (every 2nd call: tau 5.8 ms), no zipper
        sub     b,a
        asr     #$3,a,a
        add     a,b
        move    b,{GG}
        bra     fgsame
fgfin:
        move    {WT},a
        tst     a
        beq     fgsame
        move    a,x0
        clr     b
        move    b,{WT}
        move    {=KW},y0
        mpy     y0,x0,a                 ; (2 pi hz / fs) / (32 ln 2)
        bsr     fgexp
        move    #>$7fffff,a
        sub     b,a
        move    a,{LPA}                 ; 1 - e^-w
        bra     fgsame
fgchk:
        move    {AMH},a
        move    {ALAST},x0
        cmp     x0,a
        bne     fgnew
        move    x:(r6+$2),a
        move    {DLAST},x0
        cmp     x0,a
        beq     fgsame
fgnew:
        move    {AMH},x0
        move    x0,{ALAST}
        move    x:(r6+$2),y1
        move    y1,{DLAST}
        mpy     x0,y1,a
        asr     #$3,a,a                 ; (octaves down)/32 = amt x v/1024
        move    a1,a
        bsr     fgexp
        move    b,x0                    ; hz / 18 kHz
        move    x0,{WT}
fgsame:
; ---- digital silence: a call whose first frame is 0 on both sides counts; after {=GATES} s of them each call
; is looked at whole and, if every word is 0, skipped (out = in = 0): what the floored lines keep (DC of a few
; LSB) never reaches the output, and the tail ends in exact silence. Sound resets the count.
        move    #>$1,n0
        move    x:(r0),a
        move    x:(r0+n0),x0
        or      x0,a
        beq     fgzin
        clr     a
        move    a,{SIL}
        bra     fgsnd
fgzin:
        move    {SIL},a
        cmp     {=GATEN},a
        bge     fgfull
        add     #>$1,a
        move    a,{SIL}
        bra     fgsnd
fgfull:
        move    r0,r1
        clr     b
        do      n7,>fgscan
        move    x:(r1)+,x0
        or      x0,b
        move    x:(r1)+,x0
        or      x0,b
fgscan:
        nop
        tst     b
        bne     fgwoke
        rts                             ; all 0: skipped
fgwoke:
        clr     a
        move    a,{SIL}
fgsnd:
; ---- the allpass gain ramps sample by sample to the glided BLUR over the call
        move    {GG},a
        move    {GC},x0
        sub     x0,a
        asr     #$4,a,a
        move    a,{DG}
; ======== the frames ========
        move    r6,{R6S}
{=PLOAD}        move    #>$1,n0
        do      n7,>fgframes
        move    {GC},a
        move    {DG},x0
        add     x0,a
        move    a,{GC}
        move    a,y0
        move    {WM},a
        move    {DW},x0
        add     x0,a
        move    a,{WM}
        move    x:(r0),a
        asr     {=SHIFT},a,a
        move    x:(r0+n0),b
        asr     {=SHIFT},b,b
{=STAGES}; the highs sink
        move    {LPA},y1
        move    {LPL},x0
        sub     x0,a
        move    a,x1
        mpy     y1,x1,a
        add     x0,a
        move    a,{LPL}
        move    {LPR},x0
        sub     x0,b
        move    b,x1
        mpy     y1,x1,b
        add     x0,b
        move    b,{LPR}
; out = dry + mix (wet - dry)
        move    {WM},y1
        asl     {=SHIFT},a,a
        move    x:(r0),x0
        sub     x0,a
        asr     a
        move    a,x1
        mpy     y1,x1,a
        asl     a
        add     x0,a
        move    a,x:(r0)+
        asl     {=SHIFT},b,b
        move    x:(r0),x0
        sub     x0,b
        asr     b
        move    b,x1
        mpy     y1,x1,b
        asl     b
        add     x0,b
        move    b,x:(r0)+
fgframes:
        nop
{=PSAVE}        move    {R6S},r6
        rts
; ---- subroutine (after its callers) ----
{=EXPSUB}'''


def build(out='fog.asm', quiet=True):
    off = OFFSETS[out]
    total = TOTAL[out]
    for r in 'ABC':
        assert RING_WORDS[r] <= RING_ALIGN[r] and off[r] % 0x200 == 0
        assert off[r] + RING_ALIGN[r] <= total or r != 'A'
    assert total % CLR_WORDS == 0
    pinit = ''
    pload = ''
    psave = ''
    for s in range(6):
        r = RING_OF[s]
        # each pointer starts on its L line's read cell: ring start + stage offset + LEN
        pinit += (f'        move    {{YB}},a\n        add     {n(off[r] + stage_start(s) + LEN[s])},a\n'
                  f'        move    a,{{P{s}}}\n')
        pload += (f'        move    {n(RING_WORDS[r] - 1)},m{s + 1}\n        move    {{P{s}}},r{s + 1}\n'
                  f'        move    {n(LEN[s])},n{s + 1}\n')
        psave += f'        move    r{s + 1},{{P{s}}}\n        move    #>$ffffff,m{s + 1}\n'
    c = dict(
        BUILDNOTE='' if out == 'fog.asm' else '(TEST layout: rings at base + $000 / $400 / $1000)',
        STATEDOC=ST.doc(), CLRB=total // CLR_WORDS, CLRW=CLR_WORDS, CLRBN=n(total // CLR_WORDS), CLRWN=n(CLR_WORDS),
        OFFC=f'{off["C"]:03x}', OFFB=f'{off["B"]:03x}', OFFA=f'{off["A"]:03x}',
        RWA=RING_WORDS['A'], RWB=RING_WORDS['B'], RWC=RING_WORDS['C'], TOTAL=total,
        AMSNAP=n(AM_SNAP), GATES=GATE_S, GATEN=n(GATE_CALLS), SMOOTHSTEP=W.SMOOTHSTEP, BLURK=q(BLUR_K),
        KW=q(2 * math.pi * HZ_TOP / FS / math.log(2) / 32),
        SHIFT=f'#${SHIFT:x}', LPOPEN=q(lp_coef(HZ_TOP)), PINIT=pinit, PLOAD=pload, PSAVE=psave,
        STAGES=''.join(stage(k) for k in range(6)),
        EXPSUB=W.exp2_sub('fgexp', 'fgpow'),
    )
    src = W.render(W.render(TEMPLATE, ST, c), ST, c)
    W.write(HERE / out, src, quiet)
    return src


BUILDS = ('fog.asm', 'fog_test.asm')

if __name__ == '__main__':
    for b in BUILDS:
        build(b, quiet=False)
