#!/usr/bin/env python3
"""Generates the AERIA VERB source (8-line FDN reverb, a fixed-point port of
Cloudfin's FDNReverb.h).

    RING=full (default)  -> verb.asm       32,768-word ring, m = $7fff, the
                                           plugin's own line lengths
    RING=test            -> verb_test.asm  every delay length x 0.5 so the ring
                                           fits the harness's 15,870-word
                                           window (m = $3dfd)
(or: gen.py full | gen.py test | gen.py both)
"""
import math
import os
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
from asmgen import ins, q, smooth, mix, finish, e2_sub, snap_close  # noqa: E402

FS = 44100.0
LINE_MS = (43.1, 51.7, 59.3, 67.9, 76.3, 83.9, 94.7, 103.1)
AP_MS = ((4.77, 3.59, 12.73, 9.31), (5.21, 3.97, 11.83, 8.71))
DMAX = 25                 # modulation reach, samples (MOD 127 = 24.7 = 2 x 0.28 ms)
DEPTH_MAX = 2 * 0.00028 * FS
AP_G = 0.62
DAMP_A = 1.0 - math.exp(-2 * math.pi * 7500.0 / FS)
T60_MIN, T60_MAX = 0.3, 30.0
OUT_C = 0.55 * 2 * math.sqrt(8) / 4       # x4 after the sum (asl 2)
REC = 10                  # words per line record
# r7 map
S_BASE, S_PTR, S_CLR, S_MIXT, S_MIXS, S_DEPT, S_DEPS, S_DECT, S_DECS, S_TONT, S_TONS = range(11)
S_W1, S_W2, S_OL, S_OR, S_TMP = 0x0b, 0x0c, 0x0d, 0x0e, 0x0f
S_FILT = 0x10             # 2 x 16: res,x1,x2, res,a1,a2, res,b1,b2, res,c1,c2, -,d1,d2, diffused in
S_Y = 0x30                # y'[8]
S_COEF = 0x38             # 4 sections x (b0/2, b1/2, -a1/2, -a2/2)
S_APT = 0x48              # 8 x (-(read age), -(write age))
S_LINE = 0x58             # 8 x REC: eps, s hi, s lo, c hi, c lo, kconst, noff, z, g', c_i/32
S_END = S_LINE + 8 * REC


def nimm(age):
    return f'#>${(-age) & 0xffffff:06x}'


def r7(slot):
    assert 0 <= slot <= 0x3f
    return f'x:(r7+${slot:02x})'


def geometry(mode):
    """Ring layout and constants of one build ('full' or 'test')."""
    full = mode == 'full'
    scale = 1.0 if full else 0.5
    ringsize = 32768 if full else 15870
    ln = [ms * FS / 1000.0 * scale for ms in LINE_MS]          # line lengths (fractional samples)
    iln = [int(math.floor(v)) for v in ln]
    apl = [[max(1, int(ms * FS / 1000.0 * scale)) for ms in ch] for ch in AP_MS]
    age = 0
    ap_start = [[0] * 4, [0] * 4]
    for c in range(2):
        for a in range(4):
            ap_start[c][a] = age
            age += apl[c][a] + 1
    ln_start = []
    for i in range(8):
        ln_start.append(age)
        age += iln[i] + DMAX + 5
    assert age <= ringsize, (age, ringsize)
    eps = [round(2 * math.sin(math.pi * (0.07 + 0.053 * i) / FS) * (1 << 23)) / (1 << 23) for i in range(8)]
    return dict(mode=mode, full=full, scale=scale, ring=ringsize, m=ringsize - 1, used=age,
                name='verb.asm' if full else 'verb_test.asm', ln=ln, iln=iln, apl=apl,
                ap_start=ap_start, ln_start=ln_start, nclr=-(-ringsize // 256), eps=eps,
                lfo_hz=[math.asin(e / 2) * FS / math.pi for e in eps])


def build(mode):
    G = geometry(mode)
    full, ringsize, M, name, used, nclr = G['full'], G['ring'], G['m'], G['name'], G['used'], G['nclr']
    ln, iln, apl, ap_start, ln_start = G['ln'], G['iln'], G['apl'], G['ap_start'], G['ln_start']
    mimm = f'#>${M:06x}'

    lab = [0]

    def trunc0(acc):
        """acc (a fresh product / sum, N valid) -> toward zero: +1 LSB when negative."""
        lab[0] += 1
        l = f'vtz{lab[0]:02d}'
        return [ins('bpl', l), ins('add', '#>$1', acc), f'{l}:']

    H = f'''; CYCLES_FORWARD_BRANCHES
; AERIA VERB ({'full size' if full else 'TEST size: every delay length x 0.5'}) -- generated by verb/gen.py, do not edit.
; Fixed-point port of Cloudfin's 8-line FDN reverb (FDNReverb.h), 44.1 kHz.
;
;  in/4 -> HP (4th-order Butterworth, 2 biquads) -> LP (4th-order, 2 biquads)
;       -> 4 Schroeder allpasses per side (g {AP_G}) -> lines (L even, R odd)
;  8 lines read with 4-point Hermite, each modulated by its own sine LFO
;  (0.07 + 0.053 i Hz, phase 0.77 i), one-pole 7.5 kHz damping, gain from T60,
;  Hadamard 8x8, two output sign patterns x 0.55.
;
;  DECY  T60 {T60_MIN} .. {T60_MAX:g} s (log)
;  TONE  DJ filter, 64 = centre (HP 500 Hz): left HP -> 50 Hz and LP 20 k -> 302 Hz,
;        right HP -> 5 kHz
;  MOD   modulation depth 0 .. {DEPTH_MAX:.1f} samples peak (64 = the plugin's 0.28 ms)
;  MIX   0 = exact dry
;
; Line level is the plugin's / 2 (the output sum clips long before a line
; does); y' = y / sqrt(8) so the Hadamard
; butterflies need no multiply. Every quantiser inside a feedback loop rounds
; toward zero, the biquads carry their truncation residue (first-order error
; feedback), so silence in decays to exact silence.
;
; One ring of {ringsize} words in Y (m = ${M:04x}), {used} used; ages:
''' + ''.join(f';   AP{"LR"[c]}{a} {ap_start[c][a]:5d} .. {ap_start[c][a] + apl[c][a]:5d}  ({apl[c][a]} samples)\n'
              for c in range(2) for a in range(4)) \
        + ''.join(f';   LN{i}  {ln_start[i]:5d} .. {ln_start[i] + iln[i] + DMAX + 4:5d}  ({ln[i]:.2f} samples)\n'
                  for i in range(8)) + f''';
; r7 (${S_END:02x} words used): 00 base 01 ptr 02 clear count 03/04 mix t/s
;   05/06 depth t/s (samples/32) 07/08 decay t/s (log2(T60/0.3)/32)
;   09/0a tone t/s (t/2) 0b 0c scratch (w1 w2) 0d 0e out L R 0f scratch
;   10..2f filter state L, R (16 each; +15 = diffused input)
;   30..37 y'  38..47 biquad coefficients  48..57 allpass offsets
;   58.. line k at +{REC}k: eps, sin hi lo, cos hi lo, kconst, noff, z, g', c/32
'''
    L = [H]
    # ------------------------------------------------------------------ init
    L += ['init:', ins('move', '#>$ffffff', 'm4'), ins('move', 'r7', 'r4'), ins('clr', 'a'),
          ins('do', '#256', '>vizero'), ins('move', 'a', 'x:(r4)+'), 'vizero:', ins('nop'),
          ins('move', 'x:>$213', 'r4'), ins('move', 'x:(r4)', 'a'), ins('move', 'a', r7(S_BASE)),
          ins('move', 'a', r7(S_PTR)), ins('move', f'#>${nclr:06x}', 'a'), ins('move', 'a', r7(S_CLR)),
          ins('move', 'r7', 'r4'), ins('move', f'#>${S_APT:06x}', 'n4'), ins('move', '(r4)+n4'),
          ins('clr', 'b')]

    def put(imm):
        return [ins('move', imm, 'x0'), ins('move', 'x0', 'x:(r4)+')]

    for c in range(2):
        for a in range(4):
            L += put(nimm(ap_start[c][a] + apl[c][a])) + put(nimm(ap_start[c][a]))
    for i in range(8):
        eps = G['eps'][i]
        ph = 0.77 * i
        frac = ln[i] - iln[i]
        L += put(q(eps)) + put(q(0.5 * math.sin(ph))) + [ins('move', 'b', 'x:(r4)+')] \
            + put(q(0.5 * math.cos(ph))) + [ins('move', 'b', 'x:(r4)+')] \
            + put(q((frac + DMAX + 1) / 64)) + put(nimm(ln_start[i] + iln[i] - DMAX - 1)) \
            + [ins('move', 'b', 'x:(r4)+'), ins('move', 'b', 'x:(r4)+')] \
            + put(q(3 * math.log2(10) * ln[i] / (FS * T60_MIN) / 32))
    L += [ins('rts')]

    # ------------------------------------------------------------------ proc
    L += ['proc:']
    for m in ('m1', 'm2', 'm3', 'm4'):
        L += [ins('move', '#>$ffffff', m)]
    L += ['; ---- knob targets ----',
          ins('move', 'x:(r6+$5)', 'a'), ins('move', '#>$7f0000', 'x0'), ins('cmp', 'x0', 'a'),
          ins('bne', 'vmixset'), ins('move', '#>$7fffff', 'a'), 'vmixset:', ins('move', 'a', r7(S_MIXT)),
          ins('move', 'x:(r6+$2)', 'x0'), ins('move', q(DEPTH_MAX * 128 / 127 / 32), 'y0'),
          ins('mpy', 'y0', 'x0', 'a'), ins('move', 'a', r7(S_DEPT), c='depth, samples/32'),
          ins('move', 'x:(r6)', 'x0'),
          ins('move', q(math.log2(T60_MAX / T60_MIN) * 128 / 127 / 32), 'y0'),
          ins('mpy', 'y0', 'x0', 'a'), ins('move', 'a', r7(S_DECT), c='log2(T60/0.3)/32'),
          ins('move', 'x:(r6+$1)', 'a'), ins('sub', '#>$400000', 'a'), ins('tst', 'a'),
          ins('ble', 'vtonset'), ins('move', 'a', 'x0'), ins('move', q(1 / 63), 'y0'),
          ins('mac', 'y0', 'x0', 'a', c='right half: 127 -> t = +1'),
          'vtonset:', ins('move', 'a', r7(S_TONT), c='t/2')]
    L += snap_close(S_MIXT, S_MIXS, 'vsnapm') + snap_close(S_DEPT, S_DEPS, 'vsnapd') \
        + snap_close(S_DECT, S_DECS, 'vsnapt') + snap_close(S_TONT, S_TONS, 'vsnapo')
    L += ['; ---- ring clear: 256 words a call, dry passes meanwhile ----',
          ins('move', r7(S_CLR), 'a'), ins('tst', 'a'), ins('beq', 'vready'),
          ins('sub', '#>$1', 'a'), ins('move', 'a', r7(S_CLR))]
    for t, s in ((S_MIXT, S_MIXS), (S_DEPT, S_DEPS), (S_DECT, S_DECS), (S_TONT, S_TONS)):
        L += [ins('move', r7(t), 'b'), ins('move', 'b', r7(s))]
    L += [ins('asl', '#$8', 'a', 'a'), ins('move', r7(S_BASE), 'x0'), ins('add', 'x0', 'a'),
          ins('move', 'a', 'r4'), ins('move', mimm, 'm4'), ins('clr', 'a'),
          ins('do', '#256', '>vclrlp'), ins('move', 'a', 'y:(r4)+'), 'vclrlp:', ins('nop'),
          ins('move', '#>$ffffff', 'm4'), ins('rts')]
    L += ['vready:', '; ---- per call: decay -> eight line gains ----']
    L += smooth(S_DECT, S_DECS, 6) + smooth(S_TONT, S_TONS, 4)
    L += [ins('move', r7(S_DECS), 'a'), ins('bsr', 'vexp'), ins('move', 'b', r7(S_TMP), c='0.3 / T60'),
          ins('move', 'r7', 'r1'), ins('move', f'#>${S_LINE:06x}', 'n1'), ins('move', '(r1)+n1'),
          ins('move', f'#>${REC:06x}', 'n1'),
          ins('do', '#8', '>vgnend'),
          ins('move', 'x:(r1+$9)', 'y0'), ins('move', r7(S_TMP), 'x0'), ins('mpy', 'y0', 'x0', 'a'),
          ins('bsr', 'vexp', c='g = 2^-(3 log2(10) len / (fs T60))'),
          ins('move', 'b', 'x0'), ins('move', q(0.35355), 'y0'), ins('mpy', 'y0', 'x0', 'a'),
          ins('move', 'a', 'x:(r1+$8)', c="g' = g / sqrt(8)"), ins('move', '(r1)+n1'),
          'vgnend:', ins('nop')]
    L += ['; ---- per call: tone -> HP and LP biquad coefficients ----',
          ins('move', '#>$400000', 'a'), ins('move', r7(S_TONS), 'x0'), ins('sub', 'x0', 'a'),
          ins('move', 'a', 'x0'), ins('move', q(2 * math.log2(10) / 32), 'y0'), ins('mpy', 'y0', 'x0', 'a'),
          ins('bsr', 'vexp', c='10^(t-1)'),
          ins('move', 'b', 'x0'), ins('move', q(2 * math.pi * 5000 / FS / 4), 'y0'), ins('mpy', 'y0', 'x0', 'a'),
          ins('move', 'a', 'x0', c='w/4, HP 50 Hz .. 5 kHz'),
          ins('lua', f'(r7+${S_COEF:02x})', 'r3'), ins('move', '#>$1', 'a'), ins('move', 'a', r7(S_TMP)),
          ins('bsr', 'vcoef'),
          ins('move', r7(S_TONS), 'a'), ins('neg', 'a'), ins('tst', 'a'), ins('bge', 'vlppos'), ins('clr', 'a'),
          'vlppos:', ins('move', 'a', 'x0'), ins('move', q(2 * 1.82 * math.log2(10) / 32), 'y0'),
          ins('mpy', 'y0', 'x0', 'a'), ins('bsr', 'vexp', c='10^(1.82 t), t < 0'),
          ins('move', 'b', 'x0'), ins('move', q(2 * math.pi * 20000 / FS / 4), 'y0'), ins('mpy', 'y0', 'x0', 'a'),
          ins('move', q(2 * math.pi * 0.45 / 4), 'x0'), ins('cmp', 'x0', 'a'), ins('tgt', 'x0', 'a'),
          ins('move', 'a', 'x0', c='w/4, LP 302 Hz .. 0.45 fs'),
          ins('clr', 'a'), ins('move', 'a', r7(S_TMP)), ins('bsr', 'vcoef')]
    # ----------------------------------------------------------- sample loop
    L += ['; ---- sample loop ----',
          ins('move', mimm, 'm4'), ins('move', mimm, 'm5'), ins('move', r7(S_PTR), 'r5'),
          ins('do', 'n7', '>vend')]
    L += smooth(S_MIXT, S_MIXS, 7) + smooth(S_DEPT, S_DEPS, 8)
    L += [ins('lua', f'(r7+${S_FILT:02x})', 'r2'), ins('move', '#>$fffffd', 'n2'),
          ins('move', 'r7', 'r1'), ins('move', f'#>${S_APT:06x}', 'n1'), ins('move', '(r1)+n1'),
          ins('move', '#>$0', 'n0'),
          '; ---- per side: in/4, four biquads, four allpasses ----',
          ins('do', '#2', '>vchend'),
          ins('lua', f'(r7+${S_COEF:02x})', 'r3'),
          ins('move', 'x:(r0+n0)', 'a'), ins('asr', '#$2', 'a', 'a'), ins('move', 'a', 'x0'),
          ins('do', '#4', '>vbqend'),
          ins('clr', 'a'), ins('move', 'x:(r2)+', 'a0', c='residue of the last truncation'),
          ins('asr', 'a'),
          ins('move', 'x:(r3)+', 'y1'), ins('mac', 'x0', 'y1', 'a', c='b0/2 u0'),
          ins('move', 'x:(r2)', 'x1'), ins('move', 'x0', 'x:(r2)+'),
          ins('move', 'x:(r3)+', 'y0'), ins('mac', 'x1', 'y0', 'a', c='b1/2 u1'),
          ins('move', 'x:(r2)', 'x0'), ins('move', 'x1', 'x:(r2)+'),
          ins('mac', 'x0', 'y1', 'a', c='b0/2 u2'),
          ins('move', 'x:(r3)+', 'y0'), ins('move', 'x:(r2+$1)', 'x1'), ins('mac', 'x1', 'y0', 'a', c='-a1/2 v1'),
          ins('move', 'x:(r3)+', 'y0'), ins('move', 'x:(r2+$2)', 'x1'), ins('mac', 'x1', 'y0', 'a', c='-a2/2 v2'),
          ins('asl', 'a'), ins('move', 'a0', 'x:(r2+n2)'), ins('move', 'a', 'x0'),
          'vbqend:',
          ins('move', '(r2)+'), ins('move', 'x:(r2)', 'x1'), ins('move', 'x0', 'x:(r2)+'),
          ins('move', 'x1', 'x:(r2)+'),
          ins('move', 'x0', 'a'), ins('move', q(AP_G), 'y1'),
          ins('do', '#4', '>vapend'),
          ins('move', 'x:(r1)+', 'n5'), ins('move', 'y:(r5+n5)', 'x0', c='allpass end'),
          ins('mpy', 'x0', 'y1', 'b')] + trunc0('b') + [
          ins('add', 'b', 'a'), ins('move', 'x:(r1)+', 'n5'), ins('move', 'a', 'y:(r5+n5)'),
          ins('move', 'a', 'x1'), ins('move', 'x0', 'a'), ins('mac', '-y1', 'x1', 'a'),
          'vapend:',
          ins('move', 'a', 'x:(r2)+', c='diffused input'), ins('move', '#>$1', 'n0'),
          'vchend:',
          '; ---- eight lines: LFO, Hermite read, damping, gain ----',
          ins('lua', f'(r7+${S_Y:02x})', 'r3'), ins('move', f'#>${REC:06x}', 'n1'),
          ins('do', '#8', '>vlnend'),
          ins('move', 'x:(r1+$0)', 'y0', c='eps'),
          ins('move', 'x:(r1+$1)', 'a'), ins('move', 'x:(r1+$2)', 'a0'),
          ins('move', 'x:(r1+$3)', 'x0'), ins('mac', 'y0', 'x0', 'a', c='sin += eps cos'),
          ins('move', 'a1', 'x:(r1+$1)'), ins('move', 'a0', 'x:(r1+$2)'), ins('move', 'a1', 'x0'),
          ins('move', 'x:(r1+$3)', 'b'), ins('move', 'x:(r1+$4)', 'b0'),
          ins('mac', '-y0', 'x0', 'b', c='cos -= eps sin'),
          ins('move', 'b1', 'x:(r1+$3)'), ins('move', 'b0', 'x:(r1+$4)'),
          ins('move', r7(S_DEPS), 'y1'), ins('mpy', 'x0', 'y1', 'a'),
          ins('move', 'x:(r1+$5)', 'x1'), ins('add', 'x1', 'a', c='(frac + D + 1 + mod)/64 > 0'),
          ins('move', 'a1', 'b'), ins('asr', '#$11', 'a', 'a'), ins('move', 'a1', 'a', c='whole samples'),
          ins('and', '#>$01ffff', 'b'), ins('asl', '#$6', 'b', 'b'), ins('move', 'b1', 'x0', c='T toward older'),
          ins('neg', 'a'), ins('move', 'x:(r1+$6)', 'x1'), ins('add', 'x1', 'a'), ins('move', 'a1', 'n5'),
          ins('lua', '(r5+n5)', 'r4', c='-> x[-1]'),
          ins('mpy', 'x0', 'x0', 'a'), ins('move', 'a', 'x1', c='T^2'),
          ins('mpy', 'x1', 'x0', 'a'), ins('sub', 'x1', 'a'), ins('asr', 'a'),
          ins('move', 'a', 'y0', c='w2 = (T^3 - T^2)/2'), ins('move', 'y0', r7(S_W2)),
          ins('move', 'x0', 'b'), ins('sub', 'x1', 'b'), ins('asr', 'b', c='B = (T - T^2)/2'),
          ins('move', 'y0', 'a'), ins('add', 'b', 'a'), ins('neg', 'a'),
          ins('move', 'a', 'y1', c='w-1 = -w2 - B'),
          ins('sub', 'y0', 'a'), ins('sub', 'y0', 'a'), ins('add', 'x0', 'a'),
          ins('move', 'a', r7(S_W1), c='w1 = w-1 - 2 w2 + T'),
          ins('asl', 'b'), ins('add', 'y0', 'b'), ins('add', 'y0', 'b'), ins('add', 'y0', 'b'),
          ins('sub', 'x0', 'b'), ins('move', 'b', 'y0', c='w0 - 1 = 3 w2 + 2B - T'),
          ins('move', 'y:(r4)-', 'x1'), ins('move', 'y:(r4)-', 'x0'), ins('move', 'x0', 'a'),
          ins('mac', 'y1', 'x1', 'a'), ins('mac', 'y0', 'x0', 'a'),
          ins('move', 'y:(r4)-', 'x1'), ins('move', r7(S_W1), 'y1'), ins('mac', 'y1', 'x1', 'a'),
          ins('move', 'y:(r4)-', 'x0'), ins('move', r7(S_W2), 'y0'), ins('mac', 'y0', 'x0', 'a')] \
        + trunc0('a') + [
          ins('move', 'a', 'x0'), ins('move', 'x:(r1+$7)', 'b'), ins('move', 'x0', 'a'), ins('sub', 'b', 'a'),
          ins('move', 'a', 'x1'), ins('move', q(DAMP_A), 'y0'), ins('mac', 'x1', 'y0', 'b'),
          ins('move', 'b', 'x0'), ins('move', 'x0', 'x:(r1+$7)', c='damping z'),
          ins('move', 'x:(r1+$8)', 'y1'), ins('mpy', 'x0', 'y1', 'a')] + trunc0('a') + [
          ins('move', 'a', 'x:(r3)+', c="y'"), ins('move', '(r1)+n1'),
          'vlnend:']
    L += ['; ---- outputs ----', ins('clr', 'a'), ins('clr', 'b'), ins('move', q(OUT_C), 'y1')]
    SL = (1, -1, 1, 1, -1, 1, -1, 1)
    # quality pass 12 Nov 2026: line 7 joins the right output in phase (the plugin has -1): the two sign
    # patterns are orthogonal, so uncorrelated lines give L/R correlation 0 and a +3 dB mono sum (the
    # plugin's patterns overlap by -2/8: correlation about -0.2, mono sum +2.3 dB on noise)
    SR = (1, 1, -1, 1, 1, -1, -1, 1)
    for i in range(8):
        L += [ins('move', r7(S_Y + i), 'x0'), ins('mac', ('' if SL[i] > 0 else '-') + 'x0', 'y1', 'a'),
              ins('mac', ('' if SR[i] > 0 else '-') + 'x0', 'y1', 'b')]
    L += [ins('asl', '#$2', 'a', 'a'), ins('move', 'a', r7(S_OL)),
          ins('asl', '#$2', 'b', 'b'), ins('move', 'b', r7(S_OR))]
    L += ['; ---- Hadamard (h = 1, 2 in place; h = 4 into the lines with the input) ----']
    for p, p2 in ((0, 1), (2, 3), (4, 5), (6, 7), (0, 2), (1, 3), (4, 6), (5, 7)):
        L += [ins('move', r7(S_Y + p), 'a'), ins('move', r7(S_Y + p2), 'x0'), ins('move', 'a', 'b'),
              ins('add', 'x0', 'a'), ins('sub', 'x0', 'b'), ins('move', 'a', r7(S_Y + p)),
              ins('move', 'b', r7(S_Y + p2))]
    L += [ins('move', r7(S_FILT + 15), 'x1', c='diffused L (in/4 = the plugin\'s 0.5 in, / 2)'),
          ins('move', r7(S_FILT + 31), 'y1')]
    for j in range(4):
        inj = 'y1' if j & 1 else 'x1'
        L += [ins('move', r7(S_Y + j), 'a'), ins('move', r7(S_Y + j + 4), 'x0'), ins('move', 'a', 'b'),
              ins('add', 'x0', 'a'), ins('sub', 'x0', 'b'), ins('add', inj, 'a'), ins('add', inj, 'b'),
              ins('move', nimm(ln_start[j]), 'n5'), ins('move', 'a', 'y:(r5+n5)'),
              ins('move', nimm(ln_start[j + 4]), 'n5'), ins('move', 'b', 'y:(r5+n5)')]
    L += ['; ---- mix ----', ins('move', r7(S_OL), 'a')] + mix(mixslot=S_MIXS) \
        + [ins('move', r7(S_OR), 'a')] + mix(mixslot=S_MIXS) + [ins('move', '(r5)+')]
    L += ['vend:', ins('nop'), ins('move', 'r5', r7(S_PTR))]
    for m in ('m4', 'm5'):
        L += [ins('move', '#>$ffffff', m)]
    L += [ins('rts')]

    # ------------------------------------------------------------ subroutines
