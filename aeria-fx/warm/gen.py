#!/usr/bin/env python3
"""Generates warm.asm (AERIA WARM: a simple warm soft clipper; the owner's stand-in for Chloaelis' tube).

    python3 warm/gen.py          (host, no dependencies) -- test.py imports this and rebuilds

Per side:  u = clamp(g x / s + b, -1, 1);  y = f(u) - f(b);  y -> 10 Hz DC blocker -> TONE one-pole lowpass -> x LEVL
  g = 10^(24 HEAT / 127 / 20)   (0 .. +24 dB of drive; small-signal gain stays g: s = the curve's slope at 0)
  SHAP 0 SOFT: f(u) = 1.5 u - 0.5 u^3            (s = 1.5,   C1 at the knee)
  SHAP 1 TAPE: f(u) = (15 u - 10 u^3 + 3 u^5)/8  (s = 1.875, C2 at the knee: rounder)
  BIAS: b = 0.25 v/127 (asymmetry -> even harmonics; f(b) is taken off, so silence stays silence)
  TONE: 1 kHz x 18^(v/127), 127 = open;   LEVL: v/64 (64 = 0 dB);   MIX: 0 = exact dry.
No oversampling, no buffer, no P table; either core. The whole signal path runs at half scale (|y/2| <= 1/2 + f(b)/2).
"""
import math
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
from asmgen import ins, q, smooth, mix, finish, snap_close  # noqa: E402

HERE = Path(__file__).resolve().parent
FS = 44100
DRIVE_DB = 24.0
GMAX = 10 ** (DRIVE_DB / 20)
SHAPES = (('SOFT', 1.5), ('TAPE', 1.875))
B_MAX = 0.25
T_LO, T_HI = 1000.0, 18000.0
DC_HZ = 10.0
GLIDE = 9                      # per-sample one-pole on drive and level: tau 512 samples (11.6 ms)
CGLIDE = 5                     # BIAS and the TONE coefficient, once a call: tau 32 calls (11.6 ms)


def gain(v):
    return GMAX ** (v / 127)


def bias(v):
    return B_MAX * v / 127


def tone_hz(v):
    return None if v >= 127 else T_LO * (T_HI / T_LO) ** (v / 127)


def curve(u, shape):
    u = max(-1.0, min(1.0, u))
    if shape == 0:
        return 1.5 * u - 0.5 * u ** 3
    return (15 * u - 10 * u ** 3 + 3 * u ** 5) / 8


def static(x, heat, bias_v, shape):
    """the transfer curve (no filters): output for a constant input x"""
    s = SHAPES[shape][1]
    b = bias(bias_v)
    return curve(gain(heat) * x / s + b, shape) - curve(b, shape)


def coef(hz):
    return 1 - math.exp(-2 * math.pi * hz / FS)


# r7 map
(GT, GC, LT, LC, MIXT, MIXC, BC, FBV, TCOEF, SHP, TOPEN, TCT) = range(12)
CH = (0x10, 0x14)              # per side: DC lp hi lo, tone lp hi lo
DCH, DCL, TLH, TLL = range(4)
USED = 0x18
ONE = '#>$7fffff'


def sl(n):
    return f'x:(r7+${n:02x})'


def sc(c, k):
    return sl(CH[c] + k)


def curve_code(shape):
    """x0 = u (Q23, clamped) -> a = f(u)/2 (56 bit). Clobbers a x1 y0."""
    if shape == 0:
        return [ins('mpy', 'x0', 'x0', 'a'), ins('move', 'a', 'y0', c='u^2'), ins('move', q(0.75), 'a'),
                ins('move', q(0.25), 'x1'), ins('mac', '-x1', 'y0', 'a'), ins('move', 'a', 'y0'),
                ins('mpy', 'y0', 'x0', 'a', c='f/2 = u (0.75 - 0.25 u^2)')]
    return [ins('mpy', 'x0', 'x0', 'a'), ins('move', 'a', 'y0', c='w = u^2'), ins('move', q(3 / 16), 'x1'),
            ins('mpy', 'x1', 'y0', 'a'), ins('sub', q(10 / 16), 'a'), ins('move', 'a', 'x1'),
            ins('mpy', 'x1', 'y0', 'a'), ins('add', q(15 / 16), 'a'), ins('move', 'a', 'y0'),
            ins('mpy', 'y0', 'x0', 'a', c='f/2 = u (15 - 10 w + 3 w^2)/16')]


def exp_sub(label, endlabel):
    from asmgen import e2_sub
    return e2_sub(label, endlabel)


def word_down(const):
    return [ins('move', 'a', 'x0'), ins('move', '#>$7f0000', 'a'), ins('move', '#>$0', 'x1'), ins('sub', 'x0', 'a'),
            ins('tlt', 'x1', 'a'), ins('move', 'a', 'x0'), ins('move', q(const), 'y0'), ins('mpy', 'y0', 'x0', 'a')]


def build():
    c_g = (128 / 127) * math.log2(GMAX) / 32
    c_t = (128 / 127) * math.log2(T_HI / T_LO) / 32
    k_t = 2 * math.pi * T_HI / FS / math.log(2) / 32
    L = [f'''; CYCLES_FORWARD_BRANCHES
; AERIA WARM -- a simple warm soft clipper (the owner's stand-in for Chloaelis' tube). Generated by warm/gen.py.
;  knob 0 HEAT  drive 0 .. +{DRIVE_DB:.0f} dB: g = {GMAX:.3f}^(v/127); the curve is fed g x / s (s = its slope at 0)
;  knob 1 TONE  one-pole lowpass {T_LO:.0f} Hz x {T_HI / T_LO:.0f}^(v/127) after the curve; 127 = open
;  knob 2 BIAS  b = {B_MAX} v/127 added before the curve, f(b) taken off after (even harmonics)
;  knob 3 SHAP  0 SOFT 1.5u - 0.5u^3 (s 1.5) / 1 TAPE (15u - 10u^3 + 3u^5)/8 (s 1.875); u clamped to +-1
;  knob 4 LEVL  output x v/64
;  knob 5 MIX   0 = exact dry
; then a {DC_HZ:.0f} Hz DC blocker. HEAT and LEVL glide a sample at a time (2^-{GLIDE}), BIAS and the TONE coefficient once a call (2^-{CGLIDE}).
''',
         'init:', ins('move', 'r7', 'r4'), ins('move', '#>$ffffff', 'm4'), ins('clr', 'a'),
         ins('do', f'#{USED}', '>wmzero'), ins('move', 'a', 'x:(r4)+'), 'wmzero:', ins('nop'), ins('rts')]
    L += ['proc:', ins('move', '#>$ffffff', 'm4'), ins('move', '#>$1', 'n0'),
          '; SHAP',
          ins('move', 'x:(r6+$3)', 'a'), ins('move', 'a', sl(SHP)),
          '; HEAT -> G = g / (16 s)',
          ins('move', 'x:(r6)', 'a')] + word_down(c_g) + [ins('bsr', '>wmexp'), ins('move', 'b', 'x0'),
          ins('move', sl(SHP), 'a'), ins('tst', 'a'), ins('bne', 'wmgtape'),
          ins('move', q(GMAX / 16 / SHAPES[0][1]), 'y0'), ins('bra', 'wmgset'),
          'wmgtape:', ins('move', q(GMAX / 16 / SHAPES[1][1]), 'y0'),
          'wmgset:', ins('mpy', 'y0', 'x0', 'a'), ins('move', 'a', sl(GT)),
          '; LEVL: gain/2 = the knob word',
          ins('move', 'x:(r6+$4)', 'a'), ins('move', 'a', sl(LT)),
          '; TONE (127 = open)',
          ins('move', 'x:(r6+$1)', 'a')] + word_down(c_t) + [ins('bsr', '>wmexp'),
          ins('move', 'b', 'x0'), ins('move', q(k_t), 'y0'), ins('mpy', 'y0', 'x0', 'a'), ins('bsr', '>wmexp'),
          ins('move', 'b', 'x0'), ins('move', ONE, 'a'), ins('sub', 'x0', 'a'), ins('move', 'a', sl(TCT)),
          ins('move', sl(TCOEF), 'b'), ins('sub', 'b', 'a'), ins('asr', f'#${CGLIDE:x}', 'a', 'a'), ins('add', 'a', 'b'),
          ins('move', 'b', sl(TCOEF), c='the coefficient glides'),
          ins('clr', 'a'), ins('move', 'x:(r6+$1)', 'b'), ins('move', '#>$7f0000', 'x0'), ins('cmp', 'x0', 'b'),
          ins('blt', 'wmtset'), ins('move', '#>$1', 'a'), 'wmtset:', ins('move', 'a', sl(TOPEN)),
          '; BIAS: glide a call (2^-3) toward 0.25 v/127, then f(b)/2 by the same code the samples use',
          ins('move', 'x:(r6+$2)', 'x0'), ins('move', q(B_MAX * 128 / 127), 'y0'), ins('mpy', 'y0', 'x0', 'a'),
          ins('move', sl(BC), 'b'), ins('sub', 'b', 'a'), ins('asr', f'#${CGLIDE:x}', 'a', 'a'), ins('add', 'a', 'b'),
          ins('move', 'b', sl(BC)), ins('move', 'x:(r6+$2)', 'x0'), ins('move', q(B_MAX * 128 / 127), 'y0'),
          ins('mpy', 'y0', 'x0', 'a'), ins('sub', 'b', 'a'), ins('abs', 'a'), ins('cmp', '#>$000040', 'a'),
          ins('bge', 'wmbok'), ins('move', 'x:(r6+$2)', 'x0'), ins('mpy', 'y0', 'x0', 'a'), ins('move', 'a', sl(BC)),
          'wmbok:', ins('move', sl(BC), 'x0'), ins('move', sl(SHP), 'a'), ins('tst', 'a'), ins('bne', 'wmfbt')] + \
        curve_code(0) + [ins('bra', 'wmfbs'), 'wmfbt:'] + curve_code(1) + ['wmfbs:', ins('move', 'a', sl(FBV)),
          '; MIX',
          ins('move', 'x:(r6+$5)', 'a'), ins('move', '#>$7f0000', 'x0'), ins('cmp', 'x0', 'a'), ins('blt', 'wmmset'),
          ins('move', ONE, 'a'), 'wmmset:', ins('move', 'a', sl(MIXT))]
    L += snap_close(MIXT, MIXC, 'wmmsnap') + snap_close(GT, GC, 'wmgsnap', thr=0x400) + snap_close(LT, LC, 'wmlsnap', thr=0x400) + snap_close(TCT, TCOEF, 'wmtsnap', thr=0x100)
    L += ['; one of four loops: SOFT / TAPE x tone / open',
          ins('move', sl(SHP), 'a'), ins('tst', 'a'), ins('bne', 'wmtapes'),
          ins('move', sl(TOPEN), 'a'), ins('tst', 'a'), ins('bne', 'wmlso'), ins('bra', 'wmlsf'),
          'wmtapes:', ins('move', sl(TOPEN), 'a'), ins('tst', 'a'), ins('bne', 'wmlto'), ins('bra', 'wmltf')]

    def chan(c, shape, opened):
        o = [f'; ---- {"left" if c == 0 else "right"} ----',
             ins('move', 'x:(r0)', 'x0'), ins('move', sl(GC), 'y0'), ins('mpy', 'y0', 'x0', 'a'),
             ins('asl', '#$4', 'a', 'a', c='g x / s'), ins('move', sl(BC), 'x1'), ins('add', 'x1', 'a', c='+ b'),
             ins('move', ONE, 'x1'), ins('cmp', 'x1', 'a'), ins('tgt', 'x1', 'a'),
             ins('move', '#>$800000', 'x1'), ins('cmp', 'x1', 'a'), ins('tlt', 'x1', 'a'), ins('move', 'a', 'x0')]
        o += curve_code(shape) + [ins('move', sl(FBV), 'x1'), ins('sub', 'x1', 'a', c='(f(u) - f(b))/2'),
                                  ins('move', 'a', 'x0'),
                                  '; DC blocker: lp += c (z - lp); z - lp (high word)',
                                  ins('move', sc(c, DCH), 'a'), ins('move', sc(c, DCL), 'a0'),
                                  ins('move', q(coef(DC_HZ)), 'y1'), ins('mac', 'x0', 'y1', 'a'),
                                  ins('move', sc(c, DCH), 'x1'), ins('mac', '-y1', 'x1', 'a'),
                                  ins('move', 'a1', sc(c, DCH)), ins('move', 'a0', sc(c, DCL)),
                                  ins('move', 'a1', 'x1'), ins('move', 'x0', 'a'), ins('sub', 'x1', 'a'), ins('move', 'a', 'x0')]
        if opened:
            o += [ins('move', 'x0', sc(c, TLH)), ins('clr', 'a'), ins('move', 'a', sc(c, TLL), c='open: the lowpass follows')]
        else:
            o += [ins('move', sc(c, TLH), 'a'), ins('move', sc(c, TLL), 'a0'), ins('move', sl(TCOEF), 'y1'),
                  ins('mac', 'x0', 'y1', 'a'), ins('move', sc(c, TLH), 'x1'), ins('mac', '-y1', 'x1', 'a'),
                  ins('move', 'a1', sc(c, TLH)), ins('move', 'a0', sc(c, TLL)), ins('move', 'a', 'x0')]
        o += [ins('move', sl(LC), 'y0'), ins('mpy', 'y0', 'x0', 'a'), ins('asl', '#$2', 'a', 'a', c='y x LEVL')]
        o += mix(mixslot=MIXC)
        return o

    for lab, shape, opened in (('wmlsf', 0, False), ('wmlso', 0, True), ('wmltf', 1, False), ('wmlto', 1, True)):
        end = 'wmend' + lab[3:]
        L += [f'{lab}:', ins('do', 'n7', f'>{end}')]
        L += smooth(MIXT, MIXC, 7) + smooth(GT, GC, GLIDE) + smooth(LT, LC, GLIDE)
        L += chan(0, shape, opened) + chan(1, shape, opened)
        L += [f'{end}:', ins('nop'), ins('rts')]
    L += exp_sub('wmexp', 'wmxpend')
    return finish(L)


if __name__ == '__main__':
    (HERE / 'warm.asm').write_text(build())
    print('wrote warm.asm')
