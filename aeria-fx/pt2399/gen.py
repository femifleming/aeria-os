    A.put(efz)
    A.com('frozen: nothing is written; the writer still moves with the clock')
    A('move', sd(R, 'IW'), 'r4')
    A('move', sd(R, 'MW'), 'r5')
    A('move', 'n3', 'n4')
    A('move', 'n3', 'n5')
    A('lua', '(r4)+n4', 'r4')
    A('lua', '(r5)+n5', 'r5')
    A('move', 'r4', sd(R, 'IW'))
    A('move', 'r5', sd(R, 'MW'))
    A.put(edone)
