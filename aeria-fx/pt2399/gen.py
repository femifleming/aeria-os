    A('move', 'x0', sd(R, 'PHA'))
    A('move', 'a', 'x0')
    A('bsr', '>ptbits')
    A('move', 'a1', cs('SC3'), c='N bits')
    for mod, ptr, dst, base_code in ((RAMW, 'IW', 'IA', 'ram'), (24, 'MW', 'MA', 'mask')):
        A('move', cs('SC3'), 'x0')
        A('move', lit(math.floor((1 << 23) / mod)), 'y0')
