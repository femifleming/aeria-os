        A('add', 'x1', 'a')
        A('move', 'a', sd(R, 'XI'))
        A('cmp', 'b', 'a', c='u - E')
        A('move', 'x:(r5)+', 'x0', c='(moves keep the flags) this bit\'s mask')
        A('move', 'x:(r4)', 'a')
        A('bgt', one)
        A('or', 'x0', 'a')
        A('eor', 'x0', 'a')
        A('move', 'a1', 'x:(r4)+', c='bit 0')
        A('sub', 'y1', 'b', c='E -= S')
        A('move', sd(R, 'HH'), 'a')
        A('asl', 'a')
        A('bra', nx)
        A.put(one)
        A('or', 'x0', 'a')
        A('move', 'a1', 'x:(r4)+', c='bit 1')
        A('add', 'y1', 'b', c='E += S')
        A('move', sd(R, 'HH'), 'a')
