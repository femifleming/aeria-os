    A('move', sd(R, 'WET'), 'a')
    A('mac', 'y0', 'x0', 'a')
    A.com('gate (ramped)')
    A('move', 'a', 'x0')
    A('move', sd(R, 'GART'), 'b')
    A('move', 'b', 'y0')
    A('mpy', 'y0', 'x0', 'a')
