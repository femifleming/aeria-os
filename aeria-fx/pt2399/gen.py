def cs(nm):
    return f'x:(r7+${CO[nm]:02x})'


def disp(off):
    d = off - MID
    return f'+${d:02x}' if d >= 0 else f'-${-d:02x}'


def sd(R, nm, k=0):
    off = (SD_[nm] if isinstance(nm, str) else nm) + k
    return f'x:({R}{disp(off)})'


def lit(v):
    return f'#>${int(v) & 0xffffff:06x}'


class Asm:
    def __init__(self, pre):
        self.L, self.n, self.pre = [], 0, pre

    def __call__(self, op, *args, c=''):
        self.L.append(ins(op, *args, c=c))

    def lab(self, tag):
        self.n += 1
        return f'{self.pre}{tag}{self.n:03d}'

    def put(self, label):
        self.L.append(label + ':')

    def com(self, text):
        self.L.append('; ' + text)

    def raw(self, lines):
        self.L += lines if isinstance(lines, list) else [lines]


def biquad(A, R, coef, hin, hout, last):
    """DF1 section on x0 -> x0 (rounded). coef = an address text maker k -> 'x:(..)'."""
    A('move', coef(0), 'y0')
    A('mpy', 'y0', 'x0', 'a')
    A('move', sd(R, hin, 0), 'y1')
    A('move', coef(1), 'y0')
    A('mac', 'y1', 'y0', 'a')
    A('move', sd(R, hin, 1), 'x1')
    A('move', coef(2), 'y0')
    A('mac', 'x1', 'y0', 'a')
    A('move', 'y1', sd(R, hin, 1))
    A('move', 'x0', sd(R, hin, 0))
    A('move', sd(R, hout, 0), 'y1')
    A('move', coef(3), 'y0')
    A('mac', '-y1', 'y0', 'a')
    A('move', sd(R, hout, 1), 'x1')
    A('move', coef(4), 'y0')
    A('mac', '-x1', 'y0', 'a')
    A('asl', 'a')
    A('rnd', 'a')
    A('move', 'a', 'x0')
    if last:
        A('move', 'y1', sd(R, hout, 1))
        A('move', 'x0', sd(R, hout, 0))


def peak_env(A, R, slot, rho):
    A('move', sd(R, slot), 'x1')
    A('move', q(rho), 'y0')
    A('mpy', 'x1', 'y0', 'b')
    A('max', 'a', 'b')
    A('move', 'b', sd(R, slot))


def edges(A, R, ph, rate):
    """phase/8 += rate/8; n = the integer part -> n3, b1 and x0; the phase keeps the fraction."""
    A('move', sd(R, ph), 'a')
    A('move', sd(R, rate), 'x0')
    A('add', 'x0', 'a')
    A('move', 'a1', 'b')
    A('asr', '#$14', 'b', 'b')
    A('move', 'b1', 'b')
    A('and', '#>$0fffff', 'a')
    A('move', 'a1', sd(R, ph))
    A('move', 'b1', 'n3')
    A('move', 'b1', 'x0')


def arr(A, R, name, dst):
    """dst = the side array name[n3]."""
    A('lua', f'({R}{disp(SD_[name + "0"])})', 'r3')
    A('move', 'x:(r3+n3)', dst)


def cvsd_tail(A, R, est, step):
    """after a head's n edges (n3) and runs (r6): E = lambda^n E, S = beta^n S + n kMin + runs (kMax - kMin)."""
    arr(A, R, 'LN', 'x0')
    A('move', sd(R, est), 'y0')
    A('mpy', 'y0', 'x0', 'a')
    A('move', 'a', sd(R, est))
    arr(A, R, 'BN', 'x0')
    A('move', sd(R, step), 'y0')
    A('mpy', 'y0', 'x0', 'a')
    arr(A, R, 'NK', 'x0')
    A('add', 'x0', 'a')
    A('move', 'r6', 'n3')
    arr(A, R, 'RK', 'x0')
    A('add', 'x0', 'a')
    A('move', 'a', sd(R, step))


def run_count(A):
    """a1 = the history just shifted (newest bit in bit 0): a run of three equal bits -> r6 + 1."""
    nr = A.lab('nr')
    A('add', '#>$1', 'a')
    A('and', '#>$6', 'a')
    A('bne', nr)
    A('move', '(r6)+')
    A.put(nr)


def side_sample(A, R, c):
    A.com('======== one side (r1 = its block, 64 words in); x:(r0) in, x:(r0)+ out ========')
    A('move', 'x:(r0)', 'a')
    A('asr', '#$3', 'a', 'a')
    A('move', sd(R, 'FB8'), 'x0')
    A('add', 'x0', 'a')
