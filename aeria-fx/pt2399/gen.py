def clock_of(T):
    """(bits a FULL-RATE sample the chip runs at, tap length in bits) for delay T (the full-rate build's units, so
    test.py's laws stand)."""
    ceq = RAMB / (T * FS)
    c = min(CAP / 2, ceq)
    return c, RAMB * c / ceq


def bw_of(c, tone=TONE_REF):
    """c in bits a full-rate sample (clock_of's)."""
    return min(0.45 * FSH, min(BW_HI, max(BW_LO, BW_K * c * FS)) * 2 ** ((tone - TONE_REF) / TONE_STEP))


def time_of(v, skew=64, right=False, tri=0.0, mod=0):
    norm = min(1.0, (v + mod * tri) / 127)
    y = norm * OCT + ((skew - 64) / 64 if right else 0)
    return T_MIN * 2 ** min(OCT, max(0.0, y))


def lfo_hz(v):
    return LFO_LO * (LFO_HI / LFO_LO) ** (v / 127)


def grit_of(v):
    return 2 ** (-(v - 64) / GRIT_STEP)


def hp_coefs(fc, qq, fs=FSH):
    w = 2 * math.pi * fc / fs
    c, al = math.cos(w), math.sin(w) / (2 * qq)
    n = 1 / (1 + al)
    return ((1 + c) * 0.5 * n, -(1 + c) * n, (1 + c) * 0.5 * n, -2 * c * n, (1 - al) * n)


def fit(fn, lo, hi, deg):
    xs = [lo + (hi - lo) * i / 400 for i in range(401)]
    n = deg + 1
    M = [[sum(x ** (i + j) for x in xs) for j in range(n)] for i in range(n)]
    b = [sum(fn(x) * x ** i for x in xs) for i in range(n)]
    for i in range(n):
        p = M[i][i]
        M[i] = [v / p for v in M[i]]
        b[i] /= p
        for j in range(n):
            if j != i:
                f = M[j][i]
                M[j] = [u - f * v for u, v in zip(M[j], M[i])]
                b[j] -= f * b[i]
    err = max(abs(sum(c * x ** k for k, c in enumerate(b)) / fn(x) - 1) for x in xs)
    return b, err


