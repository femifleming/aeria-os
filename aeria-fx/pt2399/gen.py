    A('move', 'b', 'x0')
    A('move', q(RAMB / 65536), 'y0')
    A('mpy', 'y0', 'x0', 'a')
    A.put(done)
    A('rts')
    A.put('ptseek')
    A.com('a = N (bits / 65536): head A := the writer\'s place - N; NCUR = N. word = (IW - N) mod 1835, mask = (MW - N) mod 24')
