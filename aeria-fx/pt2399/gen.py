    peak_env(A, R, 'CENV', 1 - C_REL)
    A('move', 'x:(r0)', 'a')
    A('abs', 'a')
    peak_env(A, R, 'XENV', 1 - C_REL)
    A.com('input lowpass (bw, Q 0.62; the op-amp\'s 0.99 folded in)')
    h = HIST['IN']
    biquad(A, R, lambda k: sd(R, COEFS['IN'] + k), h, h + 2, True)
    A('move', 'x0', sd(R, 'WIN'))
