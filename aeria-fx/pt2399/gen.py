    ddone, dend, np_ = A.lab('dd'), A.lab('de'), A.lab('dp')
    edges(A, R, 'PHA', 'CA')
    A('move', sd(R, 'PCNT'), 'a')
    A('tst', 'a')
    A('beq', np_)
    A('sub', 'x0', 'a', c='old-clock bits still to read')
    A('move', 'a', sd(R, 'PCNT'))
    A('bgt', np_)
    A('move', sd(R, 'CNEW'), 'a')
    A('move', 'a', sd(R, 'CA'))
    A('move', '#>$0', 'a')
    A('move', 'a', sd(R, 'PCNT'))
    A.put(np_)
    A('tst', 'b')
    A('beq', ddone)
    A('lua', f'(r7+${CO["INV0"]:02x})', 'r3')
    A('move', 'x:(r3+n3)', 'y0', c='1/n')
    A('move', sd(R, 'IA'), 'r4')
    A('move', sd(R, 'MA'), 'r5')
    A('move', sd(R, 'SD'), 'y1')
    A('move', sd(R, 'ED'), 'b')
    A('move', '#>$0', 'r6')
    A('clr', 'a')
    A('move', 'a', sd(R, 'SUM'))
    A('do', 'n3', f'>{dend}')
    if True:
        z, nx = A.lab('dz'), A.lab('dn')
        A('move', 'x:(r5)+', 'x0')
        A('move', 'x:(r4)+', 'a')
        A('and', 'x0', 'a')
        A('beq', z)
        A('add', 'y1', 'b')
        A('move', sd(R, 'HD'), 'a')
        A('asl', 'a')
        A('add', '#>$1', 'a')
        A('bra', nx)
        A.put(z)
        A('sub', 'y1', 'b')
        A('move', sd(R, 'HD'), 'a')
        A('asl', 'a')
        A.put(nx)
        A('move', 'a1', sd(R, 'HD'))
