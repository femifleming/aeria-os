#!/usr/bin/env python3
"""Generates hail.asm and hail_test.asm (AERIA HAIL: the Balloon Shop's hailstones,
MoreWeather.h `Hail`, in fixed point).

    python3 hail/gen.py          (host, no dependencies)   -- test.py imports this and rebuilds

hail.asm       the hardware build: the stones' memory starts at the word X:$213 points to (an X address)
hail_test.asm  the same source with the memory at X:$10000 (dsp_host hands out a Y base); one line differs
"""
import math
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import wxlib as W  # noqa: E402
from wxlib import q, n  # noqa: E402

HERE = Path(__file__).resolve().parent
FS = W.FS

# ---- sizes ----------------------------------------------------------------------------------------------
STONES = 6                  # (the plugin: 8)
SLOT = 1365                 # X words a stone: its slice, recorded when it is born
TOTAL = STONES * SLOT       # 8,190 words from the base (no alignment needed)
REC_MAX = SLOT // 16        # 85 calls of 16 words
TEST_XBASE = 0x10000
FIELDS = 'MODE PTR CNT U UINC ATK ATKI RATE2 LB TNEXT GAP RATIO HITS HG PL PR BASE'.split()
ALIAS = {'GLC': 'U', 'GRC': 'UINC'}         # while it sounds: this hit's gains (the recording words are free then)
STRUCT = 20
SBASE = 0x40                # the stones' words: r7 + $40 + 20 k

# ---- the plugin's constants ------------------------------------------------------------------------------
PER_S = 2.2                 # stones a second at full amount (RATE 64)
RATE_OCT = 16.0
LEN_LO, LEN_HI = 0.005, 0.030               # slice, seconds
RATES2 = (1, 2, 2, 3, 4)                    # the plugin's 0.5 1 1 1.5 2, in half steps a frame
GAP_LO, GAP_HI = 0.09, 0.22                 # first gap, seconds
RATIO_LO, RATIO_HI = 0.62, 0.78
BNCE_SPAN = 0.25                            # BNCE: +-0.25 on the ratio over the knob
RATIO_MIN, RATIO_MAX = 0.2, 0.95
HIT0, HIT_FALL = 0.9, 0.72
ATTACK = 1 / (0.0005 * FS)                  # a frame (0.5 ms rise)
SIZE_OCT = 64.0                             # SIZE: x 2^((v - 64)/64)
LB_CAP = {r2: (2 * (REC_MAX - 1)) // r2 for r2 in (1, 2, 3, 4)}     # slice calls: rec calls = (LB r2 + 1)/2 + 1 <= 85
LB_LO, LB_SPAN = LEN_LO * FS / 16, (LEN_HI - LEN_LO) * FS / 16      # 13.8 + u 68.9 calls of 16 frames


def per_second(v, amt=1.0):
    return amt * PER_S * 2 ** ((v - 64) / RATE_OCT)


def size_scale(v):
    return 2 ** ((v - 64) / SIZE_OCT)


def ratio_range(v):
    o = (v - 64) / 64 * BNCE_SPAN
    return (min(RATIO_MAX, max(RATIO_MIN, RATIO_LO + o)), min(RATIO_MAX, max(RATIO_MIN, RATIO_HI + o)))


ST = W.State('XB RNG NACT RLAST THR SZ T1 T2')


def fld(name):
    name = ALIAS.get(name, name)
    return f'x:(r5+${FIELDS.index(name):02x})' if FIELDS.index(name) else 'x:(r5)'


ADD = '''        move    x:(r0),a
        mac     y0,x0,a
        mac     y0,x0,a
        move    a,x:(r0)+
        move    x:(r0),a
        mac     x0,y1,a
        mac     x0,y1,a
        move    a,x:(r0)+
'''

TEMPLATE = r'''; CYCLES_FORWARD_BRANCHES
; AERIA HAIL {=BUILDNOTE} -- generated by hail/gen.py, do not edit.
; The Balloon Shop's hailstones (MoreWeather.h, Hail): now and then a stone is born -- a slice of
; what is playing, 5 .. 30 ms of (L + R)/2, enveloped (0.5 ms rise, (1 - t)^2 fall), read at
; 0.5 / 1 / 1 / 1.5 / 2 x speed -- hits hard somewhere between the speakers and bounces 4 .. 8
; times, each bounce sooner (x 0.62 .. 0.78) and quieter (x 0.72), like a ball dropped on a table.
; The stones are ADDED to the dry sound.
;
;  knob 0 AMT   the weather's fade 0..127 = 0..1: how often a stone is born (x RATE). At 0 none are
;               born; the ones in the air finish
;  knob 1 RATE  stones a second at full amount: 2.2 x 2^((v - 64)/16)   (64 = the plugin)
;  knob 2 SIZE  slice length x 2^((v - 64)/64)   (64 = the plugin's 5 .. 30 ms)
;  knob 3 BNCE  how well it bounces: the gap ratio 0.62 .. 0.78 shifted by (v - 64)/64 x 0.25, held to 0.2 .. 0.95
;  knob 4 WDTH  how wide the stones fall: pan = random x v/127 (114 = the plugin's 0.9)
;
; AMT 0 and no stone in the air: REST (returns at once, output = input bit for bit).
; A stone records its slice when it is born ({=SLOT} words of its own, envelope included), then plays
; it at every hit; hits start on a call (16 frames), the gaps keep their fraction. Rates 0.5 and
; 1.5 land on half frames every second frame: read with the plugin's Hermite, which there is
; (9 (b0 + b1) - (b-1 + b2))/16; whole frames are read as they are. {=STONES} stones.
;
; X: {=TOTAL} words from {=BASENOTE}; no alignment.
; r7: {=STATEDOC}; stones at r7 + ${=SBASEH} + {=STRUCT} k: {=FIELDDOC}
;     (while a stone sounds, U / UINC hold this hit's two gains)

init:
        move    #>$ffffff,m4
        move    r7,r4
        clr     a
        do      #192,>hlzero
        move    a,x:(r4)+
hlzero:
        nop
{=GETBASE}        move    a,{XB}
        move    #>$004a11,b             ; the plugin's seed
        move    b,{RNG}
        move    #>$ffffff,b
        move    b,{RLAST}
        move    r7,r5
        move    {=SBASEN},n5
        move    {=SLOTN},x0
        move    (r5)+n5
        move    {=STRUCTN},n5
        do      {=STONESN},>hlbases
        move    a,<BASE>
        add     x0,a
        move    (r5)+n5
hlbases:
        nop
        rts
proc:
        move    x:(r6),a
        tst     a
        bne     hlgo
        move    {NACT},a
        tst     a
        bne     hlfly
        rts                             ; REST: nothing touched
hlgo:
; ---- RATE (only when it moved): chance a call at full amount = 2.2 x 16/fs x 2^((v - 64)/16)
        move    x:(r6+$1),a
        move    {RLAST},x0
        cmp     x0,a
        beq     hlrsame
        move    a,{RLAST}
        move    #>$7f0000,b
        sub     a,b
        asr     #$2,b,b
        move    b1,a
        bsr     hlexp
        move    b,x0
        move    {=PTOP},y0
        mpy     y0,x0,a
        move    a,{THR}
hlrsame:
; ---- a new stone?
        move    x:(r6),x0
        move    {THR},y0
        mpy     y0,x0,a
        move    a,x1
        bsr     hlrand
        cmp     x1,a
        bge     hlfly
        move    r7,r5
        move    {=SBASEN},n5
        move    #>$0,r4
        move    (r5)+n5
        move    {=STRUCTN},n5
        do      {=STONESN},>hlfind
        move    <MODE>,a
        tst     a
        bne     hlbusy
        move    r5,r4
hlbusy:
        move    (r5)+n5
        nop
hlfind:
        move    r4,a
        tst     a
        beq     hlfly                   ; all in the air: no stone this time (the plugin does the same)
        move    r4,r5
        bsr     hlborn
hlfly:
; ======== the stones ========
        move    r0,r2
        move    r7,r5
        move    {=SBASEN},n5
        nop
        move    (r5)+n5
        move    {=STRUCTN},n5
        do      {=STONESN},>hlstones
        move    <MODE>,a
        tst     a
        beq     hlnext
        cmp     #>$000001,a
        bne     hllive
; ---- being born: 16 more words of (L + R)/2 x min(1, attack) x (1 - t)^2 into its slice
        move    r2,r0
        move    <PTR>,r1
        move    <U>,b
        move    <UINC>,y1
        do      #16,>hlrec
        move    x:(r0)+,a
        move    x:(r0)+,x0
        add     x0,a
        asr     a
        move    a,x1
        sub     y1,b
        move    #>$0,y0
        tmi     y0,b
        move    b,x0
        mpy     x0,x0,a
        move    a,x0
        move    <ATK>,a
        move    <ATKI>,y0
        add     y0,a
        move    a,y0
        move    y0,<ATK>
        mpy     y0,x0,a
        move    a,x0
        mpy     x1,x0,a
        move    a,x:(r1)+
hlrec:
        nop
        move    b,<U>
        move    r1,<PTR>
        move    <CNT>,a
        sub     #>$1,a
        move    a,<CNT>
        bgt     hlnext
        move    #>$2,a                  ; recorded: in the air, the first hit on the next call
        move    a,<MODE>
        clr     a
        move    a,<TNEXT>
        move    a,<CNT>
        bra     hlnext
hllive:
        move    <TNEXT>,a
        sub     #>$10,a
        move    a,<TNEXT>
        move    <CNT>,b
        tst     b
        bne     hlplay                  ; a hit is sounding
        tst     a
        bgt     hlnext                  ; waiting for the next
        move    <HITS>,b
        tst     b
        bne     hlhit
        move    b,<MODE>                ; its last bounce is over
        move    {NACT},b
        sub     #>$1,b
        move    b,{NACT}
        bra     hlnext
hlhit:
        sub     #>$1,b
        move    b,<HITS>
        move    <GAP>,x0
        add     x0,a
        move    a,<TNEXT>               ; the next one a gap later, the gap x ratio
        move    <RATIO>,y0
        mpy     y0,x0,a
        move    a,<GAP>
        move    <HG>,x0                 ; this hit's level on each side, the next x 0.72
        move    <PL>,y0
        mpy     y0,x0,a
        move    a,<GLC>
        move    <PR>,y0
        mpy     y0,x0,a
        move    a,<GRC>
        move    {=KFALL},y0
        mpy     y0,x0,a
        move    a,<HG>
        move    <LB>,a
        move    a,<CNT>
        move    <BASE>,a
        add     #>$1,a
        move    a,<PTR>
hlplay:
        move    r2,r0
        move    <PTR>,r1
        move    <GLC>,y0
        move    <GRC>,y1
        move    <RATE2>,a
        jclr    #0,a1,hlwhole
; rates 0.5 and 1.5: a whole frame, then the half frame between (Hermite at 0.5)
        move    a1,n1
        sub     #>$3,a
        asr     a
        move    a1,n3
        do      #8,>hlpairs
        move    x:(r1),x0
{=ADD}        move    r1,r3
        nop
        lua     (r3)+n3,r3
        nop
        move    x:(r3)+,b
        move    x:(r3)+,a
        move    x:(r3)+,x0
        add     x0,a
        move    x:(r3)+,x0
        add     x0,b
        asr     a
        asr     b
        move    a,x0
        sub     b,a
        asr     #$3,a,a
        add     x0,a
        move    a,x0
{=ADD}        move    (r1)+n1
hlpairs:
        nop
        bra     hlsung
hlwhole:
        asr     a
        move    a1,n1
        do      #16,>hlones
        move    x:(r1)+n1,x0
{=ADD}hlones:
        nop
hlsung:
        move    r1,<PTR>
        move    <CNT>,a
        sub     #>$1,a
        move    a,<CNT>
hlnext:
        move    (r5)+n5
        nop
hlstones:
        nop
        rts
; ---- subroutines (after their callers) ----
hlborn:
; a stone is born in the struct r5 points to
        move    #>$1,a
        move    a,<MODE>
        move    {NACT},a
        add     #>$1,a
        move    a,{NACT}
        move    <BASE>,a
        move    a,<PTR>
        move    #>$7fffff,a
        move    a,<U>
        clr     a
        move    a,<ATK>
        move    {=KHIT0},a
        move    a,<HG>
; speed: 0.5 1 1 1.5 2 (half steps a frame 1 2 2 3 4); with it the longest slice that fits and the attack a word
        bsr     hlrand
        move    #>$5,y0
        mpy     y0,x0,a
        move    a1,a
        cmp     #>$000002,a
        bge     hlspd
        add     #>$1,a
hlspd:
        move    a,<RATE2>
        move    {=CAP1},x1
        move    {=ATK1},y1
        cmp     #>$000001,a
        beq     hlcap
        move    {=CAP2},x1
        move    {=ATK2},y1
        cmp     #>$000002,a
        beq     hlcap
        move    {=CAP3},x1
        move    {=ATK3},y1
        cmp     #>$000003,a
        beq     hlcap
        move    {=CAP4},x1
        move    {=ATK4},y1
hlcap:
        move    y1,<ATKI>
        move    x1,{T1}
; length: (5 .. 30 ms) x SIZE, in calls of 16 frames
        move    #>$7fffff,a
        move    x:(r6+$2),x0
        sub     x0,a
        asr     #$4,a,a                 ; ((128 - v)/64)/32
        move    a1,a
        bsr     hlexp
        move    b,x0
        move    x0,{SZ}                 ; SIZE / 2
        bsr     hlrand
        move    {=LBSPAN},y0
        mpy     y0,x0,a
        add     {=LBLO},a               ; calls x 2^12
        move    a,x0
        move    {SZ},y0
        mpy     y0,x0,a
        asr     #$b,a,a
        move    a1,a
        move    {T1},x0
        cmp     x0,a
        tgt     x0,a
        move    #>$2,x0
        cmp     x0,a
        tlt     x0,a
        move    a,<LB>
; words under the envelope = LB x 8 x RATE2; calls to record = (LB x RATE2 + 1)/2 + 1
        move    a,x0
        move    <RATE2>,y0
        mpy     y0,x0,a
        asr     a
        move    a0,b
        move    b1,x0                   ; LB x RATE2
        move    x0,a
        add     #>$1,a
        asr     a
        move    a1,a
        add     #>$1,a
        move    a,<CNT>
        move    x0,b
        asl     #$3,b,b
        move    b,x0
        move    #>$1,a
        bsr     hldiv
        move    b,<UINC>
; bounces 4 .. 8, first gap 90 .. 220 ms, each next x ratio
        bsr     hlrand
        move    #>$5,y0
        mpy     y0,x0,a
        move    a1,a
        add     #>$4,a
        move    a,<HITS>
        bsr     hlrand
        move    {=GAPSPAN},y0
        mpy     y0,x0,a
        add     {=GAPLO},a
        move    a,<GAP>
        bsr     hlrand
        move    {=RSPAN},y0
        mpy     y0,x0,a
        add     {=RLO},a
        move    x:(r6+$3),b
        sub     #>$400000,b
        asr     b
        add     b,a
        move    {=RMAX},x0
        cmp     x0,a
        tgt     x0,a
        move    {=RMIN},x0
        cmp     x0,a
        tlt     x0,a
        move    a,<RATIO>
; where it falls: pan = (2 u - 1) x WDTH, equal power, x sqrt 2 (held halved)
        bsr     hlrand
        asl     a
        sub     #>$7fffff,a
        move    a,x0
        move    x:(r6+$4),y0
        mpy     y0,x0,a
        move    a,x0
        move    {=K127},y0
        mpy     y0,x0,a                 ; pan/2
        add     #>$400000,a
        move    a,x0                    ; 0.5 + 0.5 pan
        move    x0,{T2}
        bsr     hlsin
        move    a,x0
        move    {=KRT2},y0
        mpy     y0,x0,a
        asl     a
        move    a,<PR>
        move    #>$7fffff,a
        move    {T2},x0
        sub     x0,a
        move    a,x0
        bsr     hlsin
        move    a,x0
        move    {=KRT2},y0
        mpy     y0,x0,a
        asl     a
        move    a,<PL>
        rts
{=RANDSUB}{=EXPSUB}{=SINSUB}{=DIVSUB}'''


def build(out='hail.asm', quiet=True):
    test = out != 'hail.asm'
    getbase = (f'        move    {n(TEST_XBASE)},a\n' if test else
               '        move    x:>$213,r4\n        nop\n        move    x:(r4),a\n')
    c = dict(
        BUILDNOTE='(TEST: memory at X:$10000)' if test else '',
        BASENOTE='X:$10000 (test)' if test else 'the word X:$213 points to (an X address on this effect)',
        GETBASE=getbase, SLOT=SLOT, STONES=STONES, TOTAL=TOTAL, STRUCT=STRUCT, SBASEH=f'{SBASE:02x}',
        STATEDOC=ST.doc(), FIELDDOC=' '.join(f'{i:02x} {f}' for i, f in enumerate(FIELDS)),
        SBASEN=n(SBASE), SLOTN=n(SLOT), STRUCTN=n(STRUCT), STONESN=n(STONES),
        PTOP=q(PER_S * W.DT * 2 ** (63 / RATE_OCT) * 128 / 127),
        KFALL=q(HIT_FALL), KHIT0=q(HIT0),
        CAP1=n(LB_CAP[1]), CAP2=n(LB_CAP[2]), CAP3=n(LB_CAP[3]), CAP4=n(LB_CAP[4]),
        ATK1=q(2 * ATTACK / 1), ATK2=q(2 * ATTACK / 2), ATK3=q(2 * ATTACK / 3), ATK4=q(2 * ATTACK / 4),
        LBSPAN=n(round(LB_SPAN * 4096)), LBLO=n(round(LB_LO * 4096)),
        GAPSPAN=n(round((GAP_HI - GAP_LO) * FS)), GAPLO=n(round(GAP_LO * FS)),
        RSPAN=q(RATIO_HI - RATIO_LO), RLO=q(RATIO_LO), RMAX=q(RATIO_MAX), RMIN=q(RATIO_MIN),
        K127=q(0.5 * 128 / 127), KRT2=q(math.sqrt(2) / 2 * 2 / 2),
        ADD=ADD,
        RANDSUB=W.rand_sub('hlrand', '{RNG}'), EXPSUB=W.exp2_sub('hlexp', 'hlpow'), SINSUB=W.sin_sub('hlsin'),
        DIVSUB=W.div_sub('hldiv', 'hlquo'),
    )
    assert SBASE + STONES * STRUCT <= 192 and REC_MAX * 16 <= SLOT
    t = re.sub(r'<([A-Z0-9]+)>', lambda m: fld(m.group(1)), TEMPLATE)
    src = W.render(W.render(W.render(t, ST, c), ST, c), ST, c)
    W.write(HERE / out, src, quiet)
    return src


BUILDS = ('hail.asm', 'hail_test.asm')

if __name__ == '__main__':
    for b in BUILDS:
        build(b, quiet=False)
