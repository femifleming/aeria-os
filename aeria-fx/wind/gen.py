#!/usr/bin/env python3
"""Generates wind.asm (AERIA WIND: the Balloon Shop's wind, MoreWeather.h `Wind`, in fixed point).

    python3 wind/gen.py          (host, no dependencies)   -- test.py imports this and rebuilds

Importing only builds the constants; build() writes the source.
"""
import math
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import wxlib as W  # noqa: E402
from wxlib import q, n  # noqa: E402

HERE = Path(__file__).resolve().parent
FS = W.FS

# ---- sizes (the host assigns the address; the ring must start on a multiple of RING) -------------
RING = 4096                 # words: one stereo ring, L on even addresses, R on odd (2,048 frames)
CLR_BLOCKS = 16             # the ring is cleared over this many dry calls when the wind comes up
CLR_WORDS = RING // CLR_BLOCKS

# ---- the plugin's constants, at 44.1 kHz and one tick a block (16 frames) -----------------------
D_LO, D_HI = 0.002 * FS, 0.030 * FS             # the delay's range, samples (88.2 .. 1323)
D_REST = 0.012 * FS                             # where it starts (529.2)
T_LO, T_SPAN = 0.004 * FS, 0.024 * FS           # new targets: 176.4 + u * 1058.4 samples
HOLD_LO, HOLD_SPAN = 0.3 / W.DT, 1.1 / W.DT     # ticks until the next target: 0.3 .. 1.4 s
GUST_P = W.DT / 3.5                             # chance of a gust a tick (one every 3.5 s)
GUST_OCT = 16.0                                 # GUST knob: steps an octave of gust rate
ROLL_K = math.exp(-W.DT / 2.2)
ENV_A = W.pole(0.5)
LEAN_C = W.pole(0.6)
VEL_C = W.pole(0.12)
GAIN_C = 1 - math.exp(-W.BLOCK / (2000 * FS / 48000))   # plugin: 0.0005 a sample at 48 kHz (41.7 ms)
MAXV = 0.012                                    # samples a sample at full gust (1.2 % = 20.6 cents)
VUNIT = 1 << 24                                 # the velocity word counts 2^-24 samples a sample
OFS = 3                                         # the delay word holds delay + 3 (first Hermite tap)
AM_SNAP = 0x40                                  # amount under this with the knob at 0: rest


def amt_of(v):
    return v / 127


def depth_cents(v):
    """DPTH: the largest pitch drift (a full gust), cents."""
    return 1200 * math.log2(1 + MAXV * v / 64)


def gust_seconds(v):
    """GUST: mean time between gusts, seconds."""
    return 3.5 * 2 ** ((64 - v) / GUST_OCT)


def lean_gains(v, lean):
    """LEAN knob v, lean -1..1 (amount x gust lean): (left gain, right gain)."""
    k = v / 64
    return (1 - 0.35 * k * max(0, lean) + 0.12 * k * max(0, -lean),
            1 - 0.35 * k * max(0, -lean) + 0.12 * k * max(0, lean))


ST = W.State('ST YB WP AMH AML RNG ROLL ENV LEANT LEANN HOLD DTGT DH DL VL VX G2 '
             'AL BL AR BR DAL DBL DAR DBR W0 W1 W2 W3 MAXV0 GTHR GLAST GG WMIX CHL CHR LNK')

TEMPLATE = r'''; CYCLES_FORWARD_BRANCHES
; AERIA WIND -- generated by wind/gen.py, do not edit.
; The Balloon Shop's wind (MoreWeather.h, Wind): the sound is read through one delay that keeps
; drifting -- a few cents sharp, then flat, up to DPTH in a strong gust -- swells a little with
; each gust (x 0.93 .. 1.18) and leans to one side with it. Both channels read the same delay.
;
;  knob 0 AMT   the weather's fade 0..127 = 0..1: mix = smoothstep(1.5 amt), lean x amt
;  knob 1 DPTH  largest drift in a full gust, 0..2.4 % (64 = 1.2 % = 20.6 cents, the plugin)
;  knob 2 GUST  gusts: one every 3.5 s x 2^((64 - v)/16)   (64 = the plugin)
;  knob 3 LEAN  how far a gust leans the sound: x v/64 of the plugin's -35 % / +12 %
;
; AMT 0 and settled: REST, the routine returns at once (output = input, bit for bit). Coming up
; from rest the ring is cleared over {=CLRB} dry calls ({=CLRW} words each), then it runs.
; The control tick (gusts, lean, a new delay target every 0.3 .. 1.4 s, the delay's velocity,
; the swell) runs once a call (16 frames, 0.363 ms) on a 24-bit LCG.
; Read: 4-point Hermite (Catmull-Rom), the plugin's, weights computed once a frame for both sides.
;
; Y ring: {=RING} words at the base X:$213 points to; the base must be a multiple of {=RING}.
; L on even addresses, R on odd.
; r7: {=STATEDOC}

init:
        move    #>$ffffff,m4
        move    r7,r4
        clr     a
        do      #64,>wnzero
        move    a,x:(r4)+
wnzero:
        nop
        move    x:>$213,r4
        nop
        move    x:(r4),a
        move    a,{YB}
        move    a,{WP}
        move    #>$009057,a             ; the plugin's seed
        move    a,{RNG}
        move    #>$ffffff,a
        move    a,{GLAST}
        rts
proc:
        move    {ST},a
        tst     a
        bne     wnawake
        move    x:(r6),a
        tst     a
        bne     wnwake
        rts                             ; REST: nothing touched
wnwake:
; ---- up from rest: the plugin's reset values, then {=CLRB} clearing calls
        clr     a
        move    a,{AMH}
        move    a,{AML}
        move    a,{ROLL}
        move    a,{ENV}
        move    a,{LEANT}
        move    a,{LEANN}
        move    a,{HOLD}
        move    a,{DL}
        move    a,{VL}
        move    a,{VX}
        move    a,{BL}
        move    a,{BR}
        move    {=DREST},a
        move    a,{DH}
        move    a,{DTGT}
        move    #>$400000,a
        move    a,{G2}
        move    a,{AL}
        move    a,{AR}
        move    {YB},a
        move    a,{WP}
        move    x:(r6+$3),a             ; LEAN starts where the knob is (glided from here on)
        move    a,{LNK}
        move    {=CLRBN},a
        move    a,{ST}
        rts
wnawake:
        blt     wnrun
; ---- clearing: call n (16 .. 1) clears words (n - 1) * {=CLRW} ..
        sub     #>$1,a
        move    a,{ST}
        asl     {=CLRSH},a,a
        move    {YB},x0
        add     x0,a
        move    a1,r4
        move    #>$ffffff,m4
        clr     b
        do      {=CLRWN},>wnclr
        move    b,y:(r4)+
wnclr:
        nop
        move    {ST},a
        tst     a
        bne     wnkeep
        move    #>$ffffff,a             ; cleared: RUN from the next call
        move    a,{ST}
wnkeep:
        rts
wnrun:
; ---- amount: knob / 127, glided (1/64 a call = 23 ms, 48 bits); at 0 and settled -> REST
        move    x:(r6),x0
        move    #>$408102,y0
        mpy     y0,x0,a
        asl     a
        move    {AMH},b
        move    {AML},b0
        sub     b,a
        asr     #$6,a,a
        add     a,b
        move    b1,{AMH}
        move    b0,{AML}
        move    x:(r6),a
        tst     a
        bne     wngo
        move    {AMH},a
        cmp     {=AMSNAP},a
        bge     wngo
        clr     a
        move    a,{ST}
        rts
wngo:
; mix = smoothstep(min(1, 1.5 amt))
        move    {AMH},a
        move    a,b
        asr     b
        add     b,a
        move    a,x0
{=SMOOTHSTEP}        move    a,{WMIX}
; ---- GUST knob (only when it moved): threshold = p x 2^((v - 64)/16)
        move    x:(r6+$2),a
        move    {GLAST},x0
        cmp     x0,a
        beq     wngsame
        move    a,{GLAST}
        move    #>$7f0000,b
        sub     a,b
        asr     #$2,b,b                 ; y/32, y = (127 - v)/16
        move    b1,a
        bsr     wnexp
        move    b,x0
        move    {=GTOP},y0
        mpy     y0,x0,a
        move    a,{GTHR}
wngsame:
; DPTH: full-gust velocity = 0.024 x v/128 samples a sample, in 2^-24 samples
        move    x:(r6+$1),x0
        move    {=MAXV2},y0
        mpy     y0,x0,a
        move    a,{MAXV0}
; ======== the control tick ========
; a gust now and then: roll = max(roll, 0.4 + 0.6 u), a new side to lean to
        bsr     wnrand
        move    {GTHR},x1
        cmp     x1,a
        bge     wncalm
        bsr     wnrand
        move    {=K06},y0
        mpy     y0,x0,a
        add     {=K04},a
        move    {ROLL},x1
        cmp     x1,a
        tlt     x1,a
        move    a,{ROLL}
        bsr     wnrand
        asl     a
        sub     #>$7fffff,a
        move    a,{LEANT}
wncalm:
; roll dies away (2.2 s); env follows it up in 0.5 s and down at once
        move    {ROLL},x0
        move    {=ROLLK},y0
        mpy     y0,x0,a
        move    a,{ROLL}
        move    {ENV},b
        sub     b,a
        bgt     wnswell
        move    {ROLL},b
        bra     wnenvd
wnswell:
        move    a,x0
        move    {=ENVA},y0
        mpy     y0,x0,a
        add     a,b
wnenvd:
        move    b,{ENV}
        add     {=K015},b
        move    b,x0                    ; g = min(1, 0.15 + env)
        move    x0,{GG}
; lean glides to target x g (0.6 s)
        move    {LEANT},y1
        mpy     x0,y1,a
        move    {LEANN},b
        sub     b,a
        asr     a
        move    a,x1
        move    {=LEANC2},y0
        mpy     x1,y0,a
        add     a,b
        move    b,{LEANN}
; a new delay to drift to, every 0.3 .. 1.4 s
        move    {HOLD},a
        sub     #>$1,a
        move    a,{HOLD}
        bgt     wnheld
        bsr     wnrand
        move    {=HOLDSPAN},y0
        mpy     y0,x0,a
        add     {=HOLDLO},a
        move    a,{HOLD}
        bsr     wnrand
        move    {=TSPAN},y0
        mpy     y0,x0,a
        add     {=TLO},a
        move    a,{DTGT}
wnheld:
; velocity: towards (target - delay) / 0.5 s, held to the gust's limit, glided (0.12 s)
        move    {GG},x0
        move    {=K075},y0
        mpy     y0,x0,a
        add     {=K025},a
        move    a,x0
        move    {MAXV0},y0
        mpy     y0,x0,a
        move    a,x1                    ; the limit
        move    {DTGT},a
        move    {DH},x0
        sub     x0,a
        asl     #$a,a,a
        move    a,x0
        move    {=KWANT},y0
        mpy     y0,x0,a
        cmp     x1,a
        tgt     x1,a
        move    x1,b
        neg     b
        move    b,x1
        cmp     x1,a
        tlt     x1,a
        move    {VL},b
        sub     b,a
        move    a,x0
        move    {=VELC},y0
        mpy     y0,x0,a
        add     a,b
        move    b,{VL}
        move    #>$ffffff,x1
        clr     a
        tst     b
        tmi     x1,a
        move    a1,{VX}                 ; its sign, for the 48-bit add
; the swell: gain/2 glides to 0.5 + 0.125 (g - 0.3)
        move    {GG},a
        asr     #$3,a,a
        add     {=K4625},a
        move    {G2},b
        sub     b,a
        move    a,x0
        move    {=GAINC},y0
        mpy     y0,x0,a
        add     a,b
        move    b,{G2}
; ======== this call's gains: out = 2 (A dry + B wet) a side ========
; lean l = amt x leanNow x LEAN/2; the side it leans to x (1 - 0.35 l), the other x (1 + 0.12 l)
        move    {AMH},x0
        move    {LEANN},y1
        mpy     x0,y1,a
        move    a,x0
        move    x:(r6+$3),a             ; LEAN glided 1/16 a call (5.8 ms): a jumped knob must not step the gains
        move    {LNK},b
        sub     b,a
        asr     #$4,a,a
        add     a,b
        move    b,{LNK}
        move    b,y1
        mpy     x0,y1,a
        move    a,x0                    ; signed
        abs     a
        move    a,x1
        move    {=K035},y0
        mpy     x1,y0,a
        neg     a
        add     #>$400000,a
        move    {=K012},y0
        mpy     x1,y0,b
        add     #>$400000,b
        move    a,y0                    ; the side leaned to (halved)
        move    b,y1                    ; the other
        move    x0,a
        tst     a
        ble     wnleft
        move    y0,{CHL}                ; lean > 0: the plugin turns the LEFT down
        move    y1,{CHR}
        bra     wnsides
wnleft:
        move    y1,{CHL}
        move    y0,{CHR}
wnsides:
        move    {WMIX},x0
        move    {G2},y1
        mpy     x0,y1,a
        move    a,x1                    ; w x gain / 2
        move    #>$7fffff,a
        sub     x0,a
        move    a,x0                    ; 1 - w
        move    {CHL},y0
        mpy     y0,x0,a
        move    {AL},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DAL}
        mpy     x1,y0,a
        asl     a
        move    {BL},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DBL}
        move    {CHR},y0
        mpy     y0,x0,a
        move    {AR},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DAR}
        mpy     x1,y0,a
        asl     a
        move    {BR},b
        sub     b,a
        asr     #$4,a,a
        move    a,{DBR}
; ======== the frames ========
        move    {=RINGM},m1
        move    {=RINGM},m3
        move    {WP},r1
        move    #>$1,n0
        do      n7,>wnframes
; delay += velocity (48 bits: whole samples, fraction)
        move    {DH},a
        move    {DL},a0
        move    {VX},x1
        move    {VL},x0
        add     x,a
        move    a1,{DH}
        move    a0,{DL}
        move    a1,n1
        move    a1,n3
        move    a0,b
        not     b
        lsr     b
        move    b1,x0                   ; t = 1 - fraction
; Hermite weights: W0 = t2 - (t3 + t)/2, W2 = 2 t2 + (t - 3 t3)/2, W3 = (t3 - t2)/2, W1 = 1 - the rest
        mpy     x0,x0,a
        move    a,x1                    ; t2
        mpy     x1,x0,b
        move    b,y0                    ; t3
        sub     x1,b
        asr     b
        move    b,{W3}
        move    b,a
        move    y0,b
        add     x0,b
        asr     b
        neg     b
        add     x1,b
        move    b,{W0}
        add     b,a
        move    y0,b
        asl     b
        add     y0,b
        neg     b
        add     x0,b
        asr     b
        add     x1,b
        add     x1,b
        move    b,{W2}
        add     b,a
        move    #>$7fffff,b
        sub     a,b
        move    b,{W1}
; write the frame, then read 4 frames from delay + 1 back
        move    x:(r0),a
        move    a,y:(r1)+
        move    x:(r0+n0),a
        move    a,y:(r1)+
        lua     (r1)-n1,r3
        lua     (r3)-n3,r3
        clr     a
        clr     b
        move    {W0},y0
        move    y:(r3)+,x0
        mac     y0,x0,a
        move    y:(r3)+,x0
        mac     y0,x0,b
        move    {W1},y0
        move    y:(r3)+,x0
        mac     y0,x0,a
        move    y:(r3)+,x0
        mac     y0,x0,b
        move    {W2},y0
        move    y:(r3)+,x0
        mac     y0,x0,a
        move    y:(r3)+,x0
        mac     y0,x0,b
        move    {W3},y0
        move    y:(r3)+,x0
        mac     y0,x0,a
        move    y:(r3)+,x0
        mac     y0,x0,b
        move    a,x1                    ; wet L
        move    b,y1                    ; wet R
; left: 2 (A dry + B wet), A and B ramped to this call's values
        move    {AL},b
        move    {DAL},y0
        add     y0,b
        move    b,{AL}
        move    b,y0
        move    x:(r0),x0
        mpy     y0,x0,a
        move    {BL},b
        move    {DBL},y0
        add     y0,b
        move    b,{BL}
        move    b,y0
        mac     x1,y0,a
        asl     a
        move    a,x:(r0)+
; right
        move    {AR},b
        move    {DAR},y0
        add     y0,b
        move    b,{AR}
        move    b,y0
        move    x:(r0),x0
        mpy     y0,x0,a
        move    {BR},b
        move    {DBR},x0
        add     x0,b
        move    b,{BR}
        move    b,x0
        mac     x0,y1,a
        asl     a
        move    a,x:(r0)+
wnframes:
        nop
        move    r1,{WP}
        move    #>$ffffff,m1
        move    #>$ffffff,m3
; the delay stays inside 2 .. 30 ms
        move    {DH},a
        move    {=DLO},x0
        cmp     x0,a
        bge     wnlook
        move    x0,{DH}
        clr     b
        move    b,{DL}
wnlook:
        move    {=DHI},x0
        cmp     x0,a
        blt     wndone
        move    x0,{DH}
        clr     b
        move    b,{DL}
wndone:
        rts
; ---- subroutines (after their callers) ----
{=RANDSUB}{=EXPSUB}'''


def consts():
    c = dict(
        RING=RING, CLRB=CLR_BLOCKS, CLRW=CLR_WORDS, STATEDOC=ST.doc(),
        CLRBN=n(CLR_BLOCKS), CLRWN=n(CLR_WORDS), CLRSH=f'#${int(math.log2(CLR_WORDS)):x}',
        RINGM=n(RING - 1), AMSNAP=n(AM_SNAP),
        DREST=n(round(D_REST) + OFS), DLO=n(math.ceil(D_LO) + OFS), DHI=n(math.floor(D_HI) + OFS),
        SMOOTHSTEP=W.SMOOTHSTEP,
        GTOP=n(round(GUST_P * 2 ** (63 / GUST_OCT) * (1 << 23))),
        MAXV2=n(round(2 * MAXV * VUNIT)),
        K06=q(0.6), K04=q(0.4), K015=q(0.15), K075=q(0.75), K025=q(0.25),
        ROLLK=q(ROLL_K), ENVA=q(ENV_A), LEANC2=q(2 * LEAN_C), VELC=q(VEL_C), GAINC=q(GAIN_C),
        HOLDSPAN=n(round(HOLD_SPAN)), HOLDLO=n(round(HOLD_LO)),
        TSPAN=n(round(T_SPAN)), TLO=n(round(T_LO) + OFS),
        KWANT=q(VUNIT / (0.5 * FS) / 1024),
        K4625=q(0.5 + 0.125 * -0.3), K035=q(0.35), K012=q(0.12),
        RANDSUB=W.rand_sub('wnrand', '{RNG}'), EXPSUB=W.exp2_sub('wnexp', 'wnpow'),
    )
    return c


def build(out='wind.asm', quiet=True):
    c = consts()
    # the subroutine text carries {RNG}: render twice
    src = W.render(W.render(TEMPLATE, ST, c), ST, c)
    assert RING & (RING - 1) == 0 and RING <= 0x8000
    W.write(HERE / out, src, quiet)
    return src


BUILDS = {'wind.asm': {}}

if __name__ == '__main__':
    build(quiet=False)
