# the sequencer's track filters: RBJ 2-pole lowpass and high-pass at Q 1.2 (the fixed "20 %" resonance: Q runs
# 0.707 x 14^r), 128 cutoffs 20 Hz..20 kHz (log), as engine.asm's bqd wants them: b0 b1 b2 -a1 -a2, halved, Q23
import math
def co(f, hp, q=1.2):
    w = 2 * math.pi * f / 44100.0; c = math.cos(w); al = math.sin(w) / (2 * q); a0 = 1 + al
    b0 = (1 + c) / 2 if hp else (1 - c) / 2; b1 = -(1 + c) if hp else 1 - c
    v = [b0 / a0, b1 / a0, b0 / a0, 2 * c / a0, -(1 - al) / a0]
    return [int(round(x / 2 * 8388607.0)) & 0xffffff for x in v]
out = ["/* generated by dsp/seq_table.py: the sequencer's track filters, Q 1.2 (20 % resonance), 128 cutoffs 20 Hz..20 kHz */"]
for name, hp in (("sq_lp", 0), ("sq_hp", 1)):
    rows = []
    for i in range(128):
        f = 20.0 * (1000.0 ** (i / 127.0))
        rows.append("{" + ",".join("0x%06xu" % x for x in co(f, hp)) + "}")
    out.append("static const uint32_t %s[128][5] = {%s};" % (name, ",\n    ".join(rows)))
open("../src/seq_table.inc", "w").write("\n".join(out) + "\n")
