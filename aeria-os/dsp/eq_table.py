#!/usr/bin/env python3
"""The master EQ's tables (src/eq_table.inc): a bandpass for each of 128 centres 20 Hz..20 kHz (log; RBJ, constant
0 dB peak gain, Q 1.0) as the engine wants a biquad -- b0 b1 b2 -a1 -a2, halved, Q23 -- and, for -12..+12 dB, the
amount of the band added to the signal: (10^(dB/20) - 1) / 4, Q23. Run: python3 eq_table.py"""
import math, os
def q23(x): v = round(x * (1 << 23)); v = max(-(1 << 23), min((1 << 23) - 1, v)); return v & 0xffffff
rows = []
for i in range(128):
    f = 20.0 * 1000.0 ** (i / 127.0); w = 2 * math.pi * min(f, 20000.0) / 44100.0; al = math.sin(w) / (2 * 1.0)
    a0 = 1 + al; b0, b1, b2 = al / a0, 0.0, -al / a0; a1, a2 = -2 * math.cos(w) / a0, (1 - al) / a0
    rows.append([q23(b0 / 2), q23(b1 / 2), q23(b2 / 2), q23(-a1 / 2), q23(-a2 / 2)])
# the shelves: a ONE-pole lowpass / high-pass added to the signal (a 2-pole one turns the phase far enough to dig a
# 3 dB hole beside the shelf: measured on the unit, 12 Nov 2026)
lp1, hp1 = [], []
for i in range(128):
    f = 20.0 * 1000.0 ** (i / 127.0); k = math.tan(math.pi * min(f, 20000.0) / 44100.0)
    lp1.append([q23(k / (1 + k) / 2), q23(k / (1 + k) / 2), 0, q23((1 - k) / (1 + k) / 2), 0])
    hp1.append([q23(1 / (1 + k) / 2), q23(-1 / (1 + k) / 2), 0, q23((1 - k) / (1 + k) / 2), 0])
g = [q23((10 ** (db / 20.0) - 1) / 4) for db in range(-12, 13)]
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'eq_table.inc'), 'w') as f:
    f.write('/* generated by dsp/eq_table.py: the master EQ. A bandpass (Q 1, 0 dB at its centre) for each of 128 centres\n * 20 Hz..20 kHz (log): b0 b1 b2 -a1 -a2, halved, Q23; and for -12..+12 dB how much of a band is added: (A - 1) / 4, Q23 */\n')
    f.write('static const uint32_t eq_bp[128][5] = {%s};\n' % ',\n    '.join('{%s}' % ','.join('0x%06xu' % v for v in r) for r in rows))
    for nm, t in (('eq_lp1', lp1), ('eq_hp1', hp1)):
        f.write('static const uint32_t %s[128][5] = {%s};\n' % (nm, ',\n    '.join('{%s}' % ','.join('0x%06xu' % v for v in r) for r in t)))
    f.write('static const uint32_t eq_gain[25] = {%s};\n' % ','.join('0x%06xu' % v for v in g))
print('wrote src/eq_table.inc')
